#!/usr/bin/env python3
"""
gen_sysnames.py - writes libgenome/celllysis/nucleo_sysnames.c: the name of every Linux syscall number, x86-64 and i386.

The vocabulary's own tables (nucleo_sys.c) name only the syscalls that carry a capability; a reader looking at `mov eax, 60; syscall` wants the name
of 60 whether or not anything is made of it. The kernel's UAPI headers are the one authority for that, so the table is GENERATED from them and
never typed:

    gen_sysnames.py <out.c> <asm/unistd_64.h> <asm/unistd_32.h>

Only plain `#define __NR_name number` lines are read. Anything else (the `__NR_syscalls` count, the x32 bit, __NR_Linux) is not a syscall and is
skipped by name. Regenerate when the headers move on; the test (tests/lib/genome/nucleo_sysnames.c) pins known numbers of both tables and that every
capability row of nucleo_sys.c agrees with this file.
"""
import re
import sys

SKIP = {"syscalls", "Linux", "Linux_syscalls", "SYSCALL_MASK", "syscall_max"}


def read(path):
    rows = {}
    for line in open(path, encoding="utf-8", errors="replace"):
        m = re.match(r"#define\s+__NR_(\w+)\s+(\d+)\s*$", line)
        if m and m.group(1) not in SKIP:
            rows.setdefault(int(m.group(2)), m.group(1))
    return sorted(rows.items())


def emit(name, rows):
    out = ["static const struct kgenome_sysname %s[] = {" % name]
    for nr, nm in rows:
        out.append('\t{ %d, "%s" },' % (nr, nm))
    out.append("};")
    return "\n".join(out)


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    t64, t32 = read(sys.argv[2]), read(sys.argv[3])
    with open(sys.argv[1], "w") as f:
        f.write("""/*
 * nucleo_sysnames.c - THE NAME OF EVERY LINUX SYSCALL NUMBER, x86-64 and i386. GENERATED by tools/gen_sysnames.py from the kernel UAPI headers
 * (asm/unistd_64.h: %d numbers, asm/unistd_32.h: %d numbers); do not edit, regenerate.
 *
 * The vocabulary's own tables (nucleo_sys.c) name the syscalls that carry a capability and no others, which is right for matching and not enough for
 * reading code. This is the kernel's table, for naming a number that something is looking at. Ordered by number: a binary search.
 */

#include <stddef.h>

#include "nucleo.h"

struct kgenome_sysname { uint16_t nr; const char *name; };

%s

%s

static const char *sysname_find(const struct kgenome_sysname *t, size_t n, uint32_t nr)
{
	size_t lo = 0, hi = n;

	while (lo < hi) {
		size_t mid = lo + (hi - lo) / 2u;

		if (t[mid].nr < nr)
			lo = mid + 1u;
		else
			hi = mid;
	}
	return lo < n && t[lo].nr == nr ? t[lo].name : NULL;
}

const char *kgenome_nucleo_sys_name_all(unsigned bits, uint32_t nr)
{
	return bits == 64 ? sysname_find(kgenome_sysnames64, sizeof kgenome_sysnames64 / sizeof kgenome_sysnames64[0], nr)
			  : sysname_find(kgenome_sysnames32, sizeof kgenome_sysnames32 / sizeof kgenome_sysnames32[0], nr);
}
""" % (len(t64), len(t32), emit("kgenome_sysnames64", t64), emit("kgenome_sysnames32", t32)))


if __name__ == "__main__":
    main()
