#!/usr/bin/env python3
"""api_surface.py - the frozen API surface of the three libs, generated and checked.

    api_surface.py write TREE                       write TREE/docs/api_surface.txt from the built archives and headers
    api_surface.py verify TREE                      fail when TREE/docs/api_surface.txt is not what the built tree exports
    api_surface.py check BASE TREE MANIFEST         fail on any change of the surface the manifest does not allow

WHAT IS LISTED (docs/api_surface.txt, sorted, one name per line):

    symbols   every global symbol DEFINED by libkofeng.a, libkgenome.a and libkuncoat.a (nm -g --defined-only: the
              archives are the ones `make` builds: build/release/lib/libkofeng.a, build/temp/libkgenome.a and
              libkuncoat.a - `make build/temp/libkgenome.a build/temp/libkuncoat.a` makes the last two)
    headers   every function declared or defined, every typedef, every struct / union / enum tag and every member of
              a struct or union, in each *.h under libkofeng/, libgenome/ and libuncoat/ (macros and enumerators are
              not frozen here; tools/patch_gate.py lists them)

A symbol carries the flags `exports_kept` (docs/exports_kept.txt names it: it is a known export with no engine caller,
the reason is THERE and is not copied here) and `no_public_header` (no header under the three libs declares it). The
flags are information; the check compares names only.

THE CHECK. BASE/docs/api_surface.txt is the frozen surface. The surface generated from TREE is compared with it:
a name that appeared is `UNREQUESTED: api-added <list> <name>` unless the manifest has `allow api <glob>`, a name that
went is `UNREQUESTED: api-removed ...` unless `allow remove-api <glob>`. And TREE/docs/api_surface.txt must be the
surface generated from TREE (`STALE` otherwise): a patch that moves the surface carries the regenerated file.
A BASE without the file is a patch that introduces the freeze: nothing to compare, the TREE file is checked alone.
Exit 1 on any failure, 2 when the archives are not built.
"""
import fnmatch, os, re, subprocess, sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import patch_gate as pg

ARCHIVES = (('libkofeng.a', 'build/release/lib/libkofeng.a'),
            ('libkgenome.a', 'build/temp/libkgenome.a'),
            ('libkuncoat.a', 'build/temp/libkuncoat.a'))
DOC = 'docs/api_surface.txt'
SYM_TYPES = set('TDBRVWi')


def symbols(archive):
    out = subprocess.run(['nm', '-g', '--defined-only', archive], capture_output=True, text=True, check=True).stdout
    names = set()
    for ln in out.split('\n'):
        p = ln.split()
        if len(p) == 3 and p[1] in SYM_TYPES:
            names.add(p[2])
    return names


def header_files(tree):
    res = []
    for lib in ('libkofeng', 'libgenome', 'libuncoat'):
        for d, ds, fs in os.walk(os.path.join(tree, lib)):
            ds[:] = [x for x in ds if x not in pg.SKIP_DIRS]
            for f in fs:
                if f.endswith('.h'):
                    res.append(os.path.join(d, f))
    return sorted(res)


def headers(tree):
    """-> {'func': set, 'type': set, 'member': set}"""
    res = {'func': set(), 'type': set(), 'member': set()}
    for p in header_files(tree):
        with open(p, 'rb') as f:
            P = pg.parse_c(f.read().decode('utf-8', 'replace'))
        td = set(P['typedefs'])
        for n in P['decls']:
            res['type' if n in td else 'func'].add(n)
        for n, st, a, b in P["funcs"]:
            res['func'].add(n)
        for t in P['tags']:
            res['type'].add(t)
        for n, tg in P['members']:
            res['member'].add(n)
    return res


def kept_names(tree):
    p = os.path.join(tree, 'docs/exports_kept.txt')
    if not os.path.exists(p):
        return set()
    with open(p) as f:
        return set(re.findall(r'[A-Za-z_]\w+', f.read()))


def generate(tree):
    """-> (text, surface) where surface is {(section, name)}; None when an archive is not built."""
    surf = set()
    for lib, rel in ARCHIVES:
        a = os.path.join(tree, rel)
        if not os.path.exists(a):
            return None
        for n in symbols(a):
            surf.add((lib, n))
    H = headers(tree)
    for kind in H:
        for n in H[kind]:
            surf.add(('header-' + kind, n))
    kept = kept_names(tree)
    declared = H['func'] | H['type']
    lines = ['# api_surface.txt - the frozen API surface of libkofeng.a, libkgenome.a and libkuncoat.a.',
             '# GENERATED by tools/api_surface.py write; do not edit. A patch that moves the surface carries this file regenerated,',
             '# and tools/merge_gate.sh fails on any name added or removed that the patch manifest does not allow.',
             '# Flags: exports_kept = named in docs/exports_kept.txt (the reason is there); no_public_header = no header declares it.']
    secs = [l for l, _ in ARCHIVES] + ['header-func', 'header-type', 'header-member']
    for s in secs:
        names = sorted(n for (sec, n) in surf if sec == s)
        lines.append('')
        lines.append('== %s (%d)' % (s, len(names)))
        for n in names:
            fl = []
            if s.endswith('.a'):
                if n in kept:
                    fl.append('exports_kept')
                if n not in declared:
                    fl.append('no_public_header')
            lines.append(n + ('  [' + ','.join(fl) + ']' if fl else ''))
    return '\n'.join(lines) + '\n', surf


def parse_doc(path):
    surf = set()
    sec = None
    with open(path) as f:
        for ln in f:
            ln = ln.rstrip('\n')
            m = re.match(r'== (\S+) \(\d+\)', ln)
            if m:
                sec = m.group(1)
            elif ln and not ln.startswith('#') and sec:
                surf.add((sec, ln.split()[0]))
    return surf


def main(argv):
    if len(argv) == 2 and argv[0] == 'write':
        g = generate(argv[1])
        if not g:
            sys.stderr.write('archives are not built under %s\n' % argv[1])
            return 2
        p = os.path.join(argv[1], DOC)
        with open(p, 'w') as f:
            f.write(g[0])
        print('%s: %d names' % (p, len(g[1])))
        return 0
    if len(argv) == 2 and argv[0] == 'verify':
        # the tree alone: docs/api_surface.txt is what the built archives and the headers give (no base, no manifest)
        g = generate(argv[1])
        if not g:
            print('api_surface: archives are not built under %s (make; make build/temp/libkgenome.a build/temp/libkuncoat.a)' % argv[1])
            return 2
        tdoc = os.path.join(argv[1], DOC)
        have = parse_doc(tdoc) if os.path.exists(tdoc) else None
        if have != g[1]:
            print('STALE: %s %s; regenerate with tools/api_surface.py write (and say why in the manifest)' % (
                DOC, 'is missing' if have is None else 'differs from the built tree (+%d -%d)' % (len(g[1] - have), len(have - g[1]))))
            return 1
        print('api_surface: %d names, %s is current' % (len(g[1]), DOC))
        return 0
    if len(argv) == 4 and argv[0] == 'check':
        base, tree, manifest = argv[1:]
        rules = pg.load_manifest(manifest)
        g = generate(tree)
        if not g:
            print('api_surface: archives are not built under %s (make; make build/temp/libkgenome.a build/temp/libkuncoat.a)' % tree)
            return 2
        fresh = g[1]
        fails = []
        bdoc, tdoc = os.path.join(base, DOC), os.path.join(tree, DOC)
        if os.path.exists(bdoc):
            frozen = parse_doc(bdoc)
            for sec, n in sorted(fresh - frozen):
                if not pg.covered(rules, 'api', n):
                    fails.append('UNREQUESTED: api-added %s %s' % (sec, n))
            for sec, n in sorted(frozen - fresh):
                if not pg.covered(rules, 'remove-api', n):
                    fails.append('UNREQUESTED: api-removed %s %s' % (sec, n))
            note = '%d frozen, %d now, +%d -%d' % (len(frozen), len(fresh), len(fresh - frozen), len(frozen - fresh))
        else:
            note = 'base has no %s: this patch introduces the freeze' % DOC
        if not os.path.exists(tdoc):
            fails.append('STALE: %s is missing (tools/api_surface.py write %s)' % (DOC, tree))
        elif parse_doc(tdoc) != fresh:
            d = parse_doc(tdoc)
            fails.append('STALE: %s differs from the built tree (+%d -%d); regenerate with tools/api_surface.py write' % (
                DOC, len(fresh - d), len(d - fresh)))
        print('api_surface: %s' % note)
        for f in fails:
            print(f)
        print('RESULT: %s' % ('FAIL (%d)' % len(fails) if fails else 'PASS'))
        return 1 if fails else 0
    sys.stderr.write(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
