/*
 * famcat_store - the catalog on disk (libkofeng/verdictor/famcat_store.c) and the snapshot (famcat.c):
 *   TEXT      the exact text of a file against an oracle string (2 families, comments, types, the counter line, letter order when a
 *             deleted letter was reused), the file name, one comment line above a variant and none for a variant without one
 *   ROUNDTRIP save then load gives the same catalog (compared by value); a catalog whose last variant was deleted keeps its counter;
 *             every non-empty set of types as variants of one family (1023: three-letter suffixes)
 *   SAVE      a case-only duplicate is refused before anything is written; a deleted family's file is removed; a file that was not
 *             loaded is neither overwritten nor removed; a directory that is missing is created; a path that is not a directory and a
 *             read-only directory fail with one line and leave the catalog as it was
 *   LOAD      a file that breaks a rule is named and not loaded while the rest are; unknown lines are counted; all-or-nothing per
 *             file; a missing directory is an empty catalog; the caps (file size, line length, file count) at and past the bound
 *   SNAPSHOT  snapshot / restore / dirty, field by field, a snapshot too small is refused
 * Files live under build/kof_famcat_store_XXXXXX and are removed at the end.
 */
#define _GNU_SOURCE
#include <dirent.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <unistd.h>

#include <kofmod/kofsig.h>
#include "../../libkofeng/verdictor/famcat.h"

static int fails;

#define CK(c) do { if (!(c)) { printf("  FAIL %s:%d  %s\n", __FILE__, __LINE__, #c); fails++; } } while (0)

#define BOT (1u << KOF_MALTYPE_BOTNET)
#define TRO (1u << KOF_MALTYPE_TROJAN)
#define ROOT (1u << KOF_MALTYPE_ROOTKIT)

static char dir[128];

static struct kof_famcat_fam F[8], F2[8], FS[8];
static struct kof_famcat_var V[16], V2[16], VS[16];
static struct kof_famcat C, C2, S;
static struct kof_famcat_store ST;

static void fresh(void)
{
	memset(F, 0, sizeof F);
	memset(V, 0, sizeof V);
	kof_famcat_init(&C, F, 8, V, 16);
	kof_famcat_init(&C2, F2, 8, V2, 16);
	kof_famcat_init(&S, FS, 8, VS, 16);
	kof_famcat_store_init(&ST);
}

static void put(const char *name, const char *text, size_t n)
{
	char p[256];
	FILE *f;

	snprintf(p, sizeof p, "%s/%s", dir, name);
	f = fopen(p, "wb");
	if (f) {
		fwrite(text, 1, n, f);
		fclose(f);
	}
}

static void puts_(const char *name, const char *text)
{
	put(name, text, strlen(text));
}

/* the file's content, or NULL when it does not exist */
static char *slurp(const char *name, size_t *n)
{
	char p[256];
	FILE *f;
	char *b;
	size_t k;

	snprintf(p, sizeof p, "%s/%s", dir, name);
	f = fopen(p, "rb");
	if (!f)
		return NULL;
	b = malloc(1u << 20);
	k = fread(b, 1, (1u << 20) - 1u, f);
	fclose(f);
	b[k] = 0;
	if (n)
		*n = k;
	return b;
}

static int exists(const char *name)
{
	char p[256];
	struct stat st;

	snprintf(p, sizeof p, "%s/%s", dir, name);
	return stat(p, &st) == 0;
}

static void wipe(void)
{
	DIR *d = opendir(dir);
	struct dirent *e;

	if (!d)
		return;
	while ((e = readdir(d)) != NULL) {
		char p[512];

		if (!strcmp(e->d_name, ".") || !strcmp(e->d_name, ".."))
			continue;
		snprintf(p, sizeof p, "%s/%s", dir, e->d_name);
		unlink(p);
	}
	closedir(d);
}

static void two(void)
{
	uint32_t f, v;

	fresh();
	CK(kof_famcat_add_family(&C, "Mirai", "first seen 2016", ROOT | BOT, &f) == KOF_FAMCAT_OK);
	CK(kof_famcat_add_variant(&C, 0, NULL, BOT, 0, NULL) == KOF_FAMCAT_OK);
	CK(kof_famcat_add_variant(&C, 0, "scanner only", TRO, 0, &v) == KOF_FAMCAT_OK);
	CK(kof_famcat_delete_variant(&C, v) == KOF_FAMCAT_OK);              /* the counter stays at D */
	CK(kof_famcat_add_family(&C, "Gafgyt", NULL, TRO, &f) == KOF_FAMCAT_OK);
}

static void text(void)
{
	char b[1024], small[16];
	static const char mirai[] =
		"// Generated by Manage > Pathogens; edit by hand with care.\n"
		"KOF_MALWARE_FAMILY_NAME(\"Mirai\");\n"
		"KOF_MALWARE_NEXT_VARIANT(\"D\");\n"
		"// first seen 2016\n"
		"KOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_ROOTKIT, KOF_MALTYPE_BOTNET);\n"
		"KOF_MALWARE_VARIANT(\"B\", KOF_MALTYPE_BOTNET);\n";
	static const char gafgyt[] =
		"// Generated by Manage > Pathogens; edit by hand with care.\n"
		"KOF_MALWARE_FAMILY_NAME(\"Gafgyt\");\n"
		"KOF_MALWARE_NEXT_VARIANT(\"B\");\n"
		"KOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_TROJAN);\n";
	size_t n;

	two();
	n = kof_famcat_family_text(&C, 0, b, sizeof b);
	CK(n == strlen(mirai) && !strcmp(b, mirai));
	n = kof_famcat_family_text(&C, 1, b, sizeof b);
	CK(n == strlen(gafgyt) && !strcmp(b, gafgyt));
	CK(kof_famcat_family_text(&C, 2, b, sizeof b) == 0);
	/* a short buffer: the length is still the whole text and nothing is written past it */
	memset(small, 'x', sizeof small);
	CK(kof_famcat_family_text(&C, 0, small, 8) == strlen(mirai) && small[7] == 0 && small[8] == 'x');
	CK(kof_famcat_family_text(&C, 0, NULL, 0) == strlen(mirai));
	/* variants in letter order whatever order they were made in: delete A, reuse its letter, it is written first again */
	CK(kof_famcat_delete_variant(&C, 0) == KOF_FAMCAT_OK);
	CK(kof_famcat_add_variant(&C, 0, NULL, ROOT, 1, NULL) == KOF_FAMCAT_OK);
	kof_famcat_family_text(&C, 0, b, sizeof b);
	CK(strstr(b, "(\"A\", KOF_MALTYPE_ROOTKIT);\nKOF_MALWARE_VARIANT(\"B\"") != NULL && strstr(b, "(\"D\"") != NULL);
	{
		char nm[32];

		kof_famcat_file_name("MiRai-9_x", nm, sizeof nm);
		CK(!strcmp(nm, "mirai-9_x.c"));
		kof_famcat_file_name("Mirai", nm, 5);
		CK(nm[0] == 0);                                 /* does not fit: empty, never a cut name */
	}
}

static int same(const struct kof_famcat *a, const struct kof_famcat *b)
{
	return !kof_famcat_dirty(a, b);
}

static void roundtrip(void)
{
	uint32_t i;
	static struct kof_famcat_fam BF[2];
	static struct kof_famcat_var BV[1100];
	struct kof_famcat big, big2;
	static struct kof_famcat_fam BF2[2];
	static struct kof_famcat_var BV2[1100];
	char *t;

	fresh();
	wipe();
	two();
	CK(kof_famcat_save(&C, &ST, dir) == KOF_FAMCAT_IO_OK && ST.note[0] == 0);
	CK(exists("mirai.c") && exists("gafgyt.c") && ST.n_file == 2);
	CK(kof_famcat_load(&C2, &ST, dir) == KOF_FAMCAT_IO_OK && ST.note[0] == 0 && ST.n_bad == 0);
	/* the families are loaded in file-name order (gafgyt.c, mirai.c): compare as sets by value */
	CK(C2.n_fam == 2 && C2.n_var == 3);
	for (i = 0; i < C2.n_fam; i++) {
		uint32_t k = !strcmp(C2.fam[i].name, "Mirai") ? 0u : 1u;

		CK(C2.fam[i].next == C.fam[k].next && !strcmp(C2.fam[i].name, C.fam[k].name));
	}
	CK(C2.fam[0].next + C2.fam[1].next == 4u + 2u);     /* Mirai D = 4 (the deleted C kept its letter), Gafgyt B = 2 */
	/* a second save of the loaded catalog is byte-identical to the first */
	t = slurp("mirai.c", NULL);
	CK(kof_famcat_save(&C2, &ST, dir) == KOF_FAMCAT_IO_OK);
	{
		char *u = slurp("mirai.c", NULL);

		CK(t && u && !strcmp(t, u));
		free(u);
	}
	free(t);
	/* every non-empty set of types as a variant of one family: 1023 variants, letters up to three, round trip by value */
	memset(BF, 0, sizeof BF);
	memset(BV, 0, sizeof BV);
	memset(BF2, 0, sizeof BF2);
	memset(BV2, 0, sizeof BV2);
	kof_famcat_init(&big, BF, 2, BV, 1100);
	kof_famcat_init(&big2, BF2, 2, BV2, 1100);
	CK(kof_famcat_add_family(&big, "All", "c", BOT, NULL) == KOF_FAMCAT_OK);
	for (i = 1; i < 1u << kof_famcat_type_count(); i++) {
		uint32_t mask = 0u, t2;

		for (t2 = 0; t2 < kof_famcat_type_count(); t2++)
			if (i >> t2 & 1u)
				mask |= 1u << kof_famcat_type_value(t2);
		if (mask != BOT)
			CK(kof_famcat_add_variant(&big, 0, i % 7u ? NULL : "x y", mask, 0, NULL) == KOF_FAMCAT_OK);
	}
	CK(big.n_var == 1023u);
	wipe();
	CK(kof_famcat_save(&big, &ST, dir) == KOF_FAMCAT_IO_OK);
	CK(kof_famcat_load(&big2, &ST, dir) == KOF_FAMCAT_IO_OK && ST.note[0] == 0);
	CK(same(&big, &big2) && big2.n_var == 1023u);
	wipe();
}

static void save(void)
{
	char *t, p[256];
	uint32_t f;
	struct stat st;

	/* a case-only duplicate that got past the dialog (a hand-built catalog) is refused at Save, nothing written */
	fresh();
	wipe();
	two();
	memcpy(C.fam[1].name, "mirai", 6);
	CK(kof_famcat_save(&C, &ST, dir) == KOF_FAMCAT_IO_COLLISION && strstr(ST.note, "mirai.c") && !exists("mirai.c") &&
	   !exists("gafgyt.c"));
	/* the library's own check refuses the same names at add time */
	fresh();
	CK(kof_famcat_add_family(&C, "Mirai", NULL, BOT, &f) == KOF_FAMCAT_OK);
	CK(kof_famcat_add_family(&C, "mirai", NULL, BOT, &f) == KOF_FAMCAT_DUP_FAMILY);

	/* a deleted family's file is removed at the next Save, the other is kept */
	fresh();
	two();
	CK(kof_famcat_save(&C, &ST, dir) == KOF_FAMCAT_IO_OK && exists("gafgyt.c"));
	CK(kof_famcat_delete_family(&C, 1) == KOF_FAMCAT_OK);
	CK(kof_famcat_save(&C, &ST, dir) == KOF_FAMCAT_IO_OK && !exists("gafgyt.c") && exists("mirai.c") && ST.n_file == 1);

	/* a file that failed to load: reported, never rewritten, never removed, and a family that would take its name is refused */
	puts_("Broken.c", "this is not a pathogen file\nKOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_BOTNET);\n");
	puts_("keep.c", "KOF_MALWARE_FAMILY_NAME(\"Keep\");\nKOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_NO_SUCH_TYPE);\n");
	CK(kof_famcat_load(&C2, &ST, dir) == KOF_FAMCAT_IO_OK);
	CK(C2.n_fam == 1 && !strcmp(C2.fam[0].name, "Mirai") && ST.n_bad == 2 && strstr(ST.note, "Broken.c") && strstr(ST.note, "keep.c") &&
	   ST.n_file == 1);
	CK(kof_famcat_save(&C2, &ST, dir) == KOF_FAMCAT_IO_OK);
	t = slurp("Broken.c", NULL);
	CK(t && strstr(t, "this is not a pathogen file") && exists("keep.c"));
	free(t);
	CK(kof_famcat_add_family(&C2, "Keep", NULL, BOT, &f) == KOF_FAMCAT_OK);
	CK(kof_famcat_save(&C2, &ST, dir) == KOF_FAMCAT_IO_COLLISION && strstr(ST.note, "keep.c"));
	t = slurp("keep.c", NULL);
	CK(t && strstr(t, "NO_SUCH_TYPE"));
	free(t);
	wipe();

	/* a missing directory is created */
	snprintf(p, sizeof p, "%s/sub", dir);
	two();
	CK(kof_famcat_save(&C, &ST, p) == KOF_FAMCAT_IO_OK);
	snprintf(p, sizeof p, "%s/sub/mirai.c", dir);
	CK(stat(p, &st) == 0);
	unlink(p);
	snprintf(p, sizeof p, "%s/sub/gafgyt.c", dir);
	unlink(p);
	snprintf(p, sizeof p, "%s/sub", dir);
	rmdir(p);

	/* no directory named */
	CK(kof_famcat_save(&C, &ST, "") == KOF_FAMCAT_IO_NO_DIR && ST.note[0]);
	CK(kof_famcat_save(&C, &ST, NULL) == KOF_FAMCAT_IO_NO_DIR);

	/* a path that is a file, not a directory: one line, the catalog is as it was */
	puts_("plain", "x");
	snprintf(p, sizeof p, "%s/plain", dir);
	fresh();
	two();
	kof_famcat_snapshot(&C, &S);
	CK(kof_famcat_save(&C, &ST, p) == KOF_FAMCAT_IO_FAIL && ST.note[0] && !strchr(ST.note, '\n') && same(&C, &S));

	/* a read-only directory (root ignores the mode: skipped then) */
	if (geteuid() != 0) {
		snprintf(p, sizeof p, "%s/ro", dir);
		mkdir(p, 0755);
		chmod(p, 0555);
		CK(kof_famcat_save(&C, &ST, p) == KOF_FAMCAT_IO_FAIL && strstr(ST.note, "cannot write") && same(&C, &S));
		chmod(p, 0755);
		rmdir(p);
	} else {
		printf("  SKIP read-only directory (running as root)\n");
	}
	wipe();
}

static void load(void)
{
	static const char good[] = "KOF_MALWARE_FAMILY_NAME(\"Z\");\nKOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_BOTNET);\n";
	char *big, p[256];
	const char *why = NULL;
	uint32_t ign = 99, i;
	size_t n;

	fresh();
	wipe();
	/* a missing directory: an empty catalog; no directory named: NO_DIR */
	snprintf(p, sizeof p, "%s/nothing", dir);
	CK(kof_famcat_load(&C, &ST, p) == KOF_FAMCAT_IO_OK && C.n_fam == 0 && ST.note[0] == 0);
	CK(kof_famcat_load(&C, &ST, NULL) == KOF_FAMCAT_IO_NO_DIR);

	/* unknown lines are counted once in the one line; blank lines and the header comment are not */
	puts_("a.c", "// Generated by Manage > Pathogens; edit by hand with care.\n\nKOF_MALWARE_FAMILY_NAME(\"Aa\");\nwhat is this\n"
	      "KOF_MALWARE_NEXT_VARIANT(\"C\");\n// c1\n// c2\nKOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_BOTNET, KOF_MALTYPE_ROOTKIT);\n"
	      "int x = 1;\r\n// stray\n\nKOF_MALWARE_VARIANT(\"B\", KOF_MALTYPE_TROJAN);\r\n");
	CK(kof_famcat_load(&C, &ST, dir) == KOF_FAMCAT_IO_OK && C.n_fam == 1 && C.n_var == 2 && ST.n_ignored == 2 &&
	   !strcmp(ST.note, "2 lines ignored") && C.fam[0].next == 3u);
	CK(!strcmp(C.var[0].comment, "c1 c2") && !strcmp(C.var[0].name, "Aa_A") && C.var[0].types == (BOT | ROOT) &&
	   C.var[1].comment[0] == 0 && C.var[1].types == TRO);              /* the stray comment is not above B: it is dropped */

	/* a text, all or nothing: a good family then a bad variant leaves the catalog as it was */
	fresh();
	CK(kof_famcat_load_text(&C, good, strlen(good), &ign, &why) == 1 && ign == 0 && C.n_fam == 1);
	{
		static const char *const bad[] = {
			"KOF_MALWARE_FAMILY_NAME(\"Y\");\nKOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_PACKER);\n",    /* Packer never */
			"KOF_MALWARE_FAMILY_NAME(\"Y\");\nKOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_BOTNET);\nKOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_TROJAN);\n",
			"KOF_MALWARE_FAMILY_NAME(\"Y\");\nKOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_BOTNET);\nKOF_MALWARE_VARIANT(\"B\", KOF_MALTYPE_BOTNET);\n",
			"KOF_MALWARE_FAMILY_NAME(\"Y\");\nKOF_MALWARE_VARIANT(\"A\");\n",                       /* no type */
			"KOF_MALWARE_FAMILY_NAME(\"Y\");\nKOF_MALWARE_VARIANT(\"a\", KOF_MALTYPE_BOTNET);\n",   /* not capital letters */
			"KOF_MALWARE_FAMILY_NAME(\"Y\");\nKOF_MALWARE_VARIANT(\"AAAAAA\", KOF_MALTYPE_BOTNET);\n",
			"KOF_MALWARE_FAMILY_NAME(\"Y\");\nKOF_MALWARE_FAMILY_NAME(\"X\");\n",
			"KOF_MALWARE_FAMILY_NAME(\"Z\");\nKOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_BOTNET);\n",          /* the same family again */
			"KOF_MALWARE_FAMILY_NAME(\"z\");\n",                                                   /* the same ignoring case */
			"KOF_MALWARE_FAMILY_NAME(\"bad name\");\n",
			"KOF_MALWARE_FAMILY_NAME(\"Y\"\n",
			"KOF_MALWARE_FAMILY_NAME(\"Y\");\n// a/b\nKOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_BOTNET);\n",   /* comment rule */
			"KOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_BOTNET);\n",                                   /* before the family */
			"KOF_MALWARE_NEXT_VARIANT(\"A\");\n",
			"KOF_MALWARE_FAMILY_NAME(\"Y\");\nKOF_MALWARE_NEXT_VARIANT(\"1\");\n",
			"// only a comment\n", "",
		};

		for (i = 0; i < sizeof bad / sizeof bad[0]; i++) {
			CK(kof_famcat_load_text(&C, bad[i], strlen(bad[i]), &ign, &why) == 0 && why && why[0] && C.n_fam == 1 && C.n_var == 1);
			if (i == 0)
				CK(!strcmp(why, kof_famcat_status_text(KOF_FAMCAT_BAD_TYPE)));
		}
	}
	/* an empty comment line between two others adds no blank (found by the fuzz adapter: the text did not read back the same) */
	fresh();
	{
		static const char em[] = "KOF_MALWARE_FAMILY_NAME(\"E\");\n// a\n//\n// b\n//\nKOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_BOTNET);\n";
		char b[256];

		CK(kof_famcat_load_text(&C, em, sizeof em - 1u, NULL, NULL) == 1 && !strcmp(C.var[0].comment, "a b"));
		kof_famcat_family_text(&C, 0, b, sizeof b);
		CK(strstr(b, "// a b\n") != NULL);
	}
	fresh();
	CK(kof_famcat_load_text(&C, good, strlen(good), &ign, &why) == 1);
	/* a NUL inside a line is a line not understood, not the end of the file */
	{
		static const char nul[] = "KOF_MALWARE_FAMILY_NAME(\"Q\");\nab\0cd\nKOF_MALWARE_VARIANT(\"A\", KOF_MALTYPE_BOTNET);\n";

		CK(kof_famcat_load_text(&C, nul, sizeof nul - 1u, &ign, &why) == 1 && ign == 1 && C.n_fam == 2 && C.n_var == 2);
	}

	/* the counter only goes up: a file with next "A" and variants A, B has next C */
	fresh();
	{
		static const char nx[] = "KOF_MALWARE_FAMILY_NAME(\"N\");\nKOF_MALWARE_NEXT_VARIANT(\"A\");\nKOF_MALWARE_VARIANT(\"B\", KOF_MALTYPE_BOTNET);\n";

		CK(kof_famcat_load_text(&C, nx, sizeof nx - 1u, NULL, NULL) == 1 && C.fam[0].next == 3u);
	}

	/* caps: a line of exactly KOF_FAMCAT_LINE_MAX is read (and not understood), one more fails; the file at KOF_FAMCAT_FILE_MAX loads,
	 * one more byte is "file too big"; more files than KOF_FAMCAT_FILES_MAX are said, not silent */
	big = malloc(KOF_FAMCAT_FILE_MAX + 8u);
	memset(big, 'x', KOF_FAMCAT_LINE_MAX + 1u);
	big[KOF_FAMCAT_LINE_MAX + 1u] = '\n';
	memcpy(big + KOF_FAMCAT_LINE_MAX + 2u, good, strlen(good));
	n = KOF_FAMCAT_LINE_MAX + 2u + strlen(good);
	fresh();
	/* a line of LINE_MAX + 1 characters fails the file; with the first character cut it is exactly LINE_MAX and is only not understood */
	CK(kof_famcat_load_text(&C, big, n, &ign, &why) == 0 && !strcmp(why, "line too long") && C.n_fam == 0);
	CK(kof_famcat_load_text(&C, big + 1, n - 1u, &ign, &why) == 1 && ign == 1 && C.n_fam == 1);
	wipe();
	memcpy(big, good, strlen(good));
	memset(big + strlen(good), '\n', KOF_FAMCAT_FILE_MAX - strlen(good));
	put("fit.c", big, KOF_FAMCAT_FILE_MAX);
	big[KOF_FAMCAT_FILE_MAX] = '\n';
	put("over.c", big, KOF_FAMCAT_FILE_MAX + 1u);
	puts_("odd.txt", good);                                       /* not *.c: never read */
	snprintf(p, sizeof p, "%s/dir.c", dir);
	mkdir(p, 0755);                                               /* a directory named *.c is not a file */
	fresh();
	CK(kof_famcat_load(&C, &ST, dir) == KOF_FAMCAT_IO_OK && C.n_fam == 1 && ST.n_bad == 2 && strstr(ST.note, "dir.c, over.c") &&
	   strstr(ST.note, "not a regular file"));
	rmdir(p);
	fresh();
	CK(kof_famcat_load(&C, &ST, dir) == KOF_FAMCAT_IO_OK && C.n_fam == 1 && ST.n_bad == 1 && strstr(ST.note, "(over.c: file too big)"));
	free(big);
	wipe();
	for (i = 0; i < KOF_FAMCAT_FILES_MAX + 3u; i++) {
		snprintf(p, sizeof p, "f%03u.c", (unsigned)i);
		puts_(p, "// nothing\n");
	}
	fresh();
	CK(kof_famcat_load(&C, &ST, dir) == KOF_FAMCAT_IO_OK && ST.n_bad == KOF_FAMCAT_FILES_MAX && strstr(ST.note, "over the limit"));
	wipe();
}

static void snapshot(void)
{
	static struct kof_famcat_fam sf[1];
	static struct kof_famcat_var sv[1];
	struct kof_famcat tiny;
	uint32_t v;

	two();
	CK(kof_famcat_dirty(&C, &S) == 1);                     /* an empty snapshot against two families */
	CK(kof_famcat_snapshot(&C, &S) == KOF_FAMCAT_OK && !kof_famcat_dirty(&C, &S));
	CK(kof_famcat_snapshot(&C, &S) == KOF_FAMCAT_OK);
	/* each field a change can touch makes it dirty, and the restore undoes it */
	CK(kof_famcat_set_comment(&C, 0, "changed") == KOF_FAMCAT_OK && kof_famcat_dirty(&C, &S));
	CK(kof_famcat_restore(&C, &S) == KOF_FAMCAT_OK && !kof_famcat_dirty(&C, &S) && !strcmp(C.var[0].comment, "first seen 2016"));
	CK(kof_famcat_set_types(&C, 1, TRO) == KOF_FAMCAT_OK && kof_famcat_dirty(&C, &S));
	CK(kof_famcat_restore(&C, &S) == KOF_FAMCAT_OK && !kof_famcat_dirty(&C, &S));
	CK(kof_famcat_rename_family(&C, 1, "Gafgyt2") == KOF_FAMCAT_OK && kof_famcat_dirty(&C, &S));
	CK(kof_famcat_restore(&C, &S) == KOF_FAMCAT_OK && !kof_famcat_dirty(&C, &S) && !strcmp(C.var[3 - 1].name, "Gafgyt_A"));
	CK(kof_famcat_add_variant(&C, 1, NULL, ROOT, 0, &v) == KOF_FAMCAT_OK && kof_famcat_dirty(&C, &S));
	CK(kof_famcat_delete_variant(&C, v) == KOF_FAMCAT_OK && kof_famcat_dirty(&C, &S));   /* the counter moved: still a change */
	CK(kof_famcat_restore(&C, &S) == KOF_FAMCAT_OK && !kof_famcat_dirty(&C, &S) && C.fam[1].next == 2u);
	CK(kof_famcat_delete_family(&C, 0) == KOF_FAMCAT_OK && kof_famcat_dirty(&C, &S));
	CK(kof_famcat_restore(&C, &S) == KOF_FAMCAT_OK && C.n_fam == 2 && C.n_var == 3 && !kof_famcat_dirty(&C, &S));
	/* the bytes after a name's terminator are not the catalog: a rename and a rename back is clean */
	CK(kof_famcat_rename_family(&C, 0, "Mi") == KOF_FAMCAT_OK && kof_famcat_rename_family(&C, 0, "Mirai") == KOF_FAMCAT_OK &&
	   !kof_famcat_dirty(&C, &S));
	/* a snapshot with tables too small is refused and changes nothing */
	kof_famcat_init(&tiny, sf, 1, sv, 1);
	CK(kof_famcat_snapshot(&C, &tiny) == KOF_FAMCAT_FULL && tiny.n_fam == 0);
	CK(kof_famcat_restore(&tiny, &C) == KOF_FAMCAT_FULL);
}

int main(void)
{
	char tmpl[] = "build/kof_famcat_store_XXXXXX";

	if (!mkdtemp(tmpl)) {
		printf("famcat_store: cannot make a scratch directory\n");
		return 1;
	}
	snprintf(dir, sizeof dir, "%s", tmpl);
	fresh();
	text();
	roundtrip();
	save();
	load();
	fresh();
	snapshot();
	wipe();
	rmdir(dir);
	printf("famcat_store: %d failure(s)\n", fails);
	return fails != 0;
}
