/* ---- a stored zip, built in memory ------------------------------------------ */

struct buf { uint8_t *p; size_t n, cap; };

static void put(struct buf *b, const void *src, size_t n)
{
	if (b->n + n > b->cap) {
		b->cap = (b->n + n) * 2u;
		b->p = realloc(b->p, b->cap);
		if (!b->p)
			exit(2);
	}
	memcpy(b->p + b->n, src, n);
	b->n += n;
}

static void p16(struct buf *b, unsigned v) { uint8_t t[2] = { (uint8_t)v, (uint8_t)(v >> 8) }; put(b, t, 2); }
static void p32(struct buf *b, uint32_t v) { p16(b, v & 0xffffu); p16(b, v >> 16); }

static uint32_t crc32_of(const uint8_t *p, size_t n)
{
	uint32_t c = 0xffffffffu;
	size_t i;
	int k;

	for (i = 0; i < n; i++) {
		c ^= p[i];
		for (k = 0; k < 8; k++)
			c = (c >> 1) ^ (0xedb88320u & (0u - (c & 1u)));
	}
	return ~c;
}

struct member { const uint8_t *p; size_t n; };

/* `n` stored members named m0..m<n-1>; the result is malloc'ed, the length in *len. */
static uint8_t *zip_stored(const struct member *m, unsigned n, size_t *len)
{
	struct buf out = { 0, 0, 0 };
	size_t *off = calloc(n, sizeof *off), cd;
	unsigned i;

	for (i = 0; i < n; i++) {
		char name[16];
		const unsigned nl = (unsigned)snprintf(name, sizeof name, "m%u", i);
		const uint32_t crc = crc32_of(m[i].p, m[i].n);

		off[i] = out.n;
		p32(&out, 0x04034b50u); p16(&out, 10); p16(&out, 0); p16(&out, 0);
		p16(&out, 0); p16(&out, 0x21); p32(&out, crc);
		p32(&out, (uint32_t)m[i].n); p32(&out, (uint32_t)m[i].n);
		p16(&out, nl); p16(&out, 0);
		put(&out, name, nl);
		put(&out, m[i].p, m[i].n);
	}
	cd = out.n;
	for (i = 0; i < n; i++) {
		char name[16];
		const unsigned nl = (unsigned)snprintf(name, sizeof name, "m%u", i);
		const uint32_t crc = crc32_of(m[i].p, m[i].n);

		p32(&out, 0x02014b50u); p16(&out, 0x031e); p16(&out, 10); p16(&out, 0); p16(&out, 0);
		p16(&out, 0); p16(&out, 0x21); p32(&out, crc);
		p32(&out, (uint32_t)m[i].n); p32(&out, (uint32_t)m[i].n);
		p16(&out, nl); p16(&out, 0); p16(&out, 0); p16(&out, 0); p16(&out, 0);
		p32(&out, 0); p32(&out, (uint32_t)off[i]);
		put(&out, name, nl);
	}
	{
		const size_t cdlen = out.n - cd;

		p32(&out, 0x06054b50u); p16(&out, 0); p16(&out, 0); p16(&out, n); p16(&out, n);
		p32(&out, (uint32_t)cdlen); p32(&out, (uint32_t)cd); p16(&out, 0);
	}
	free(off);
	*len = out.n;
	return out.p;
}

/* `n` copies of the spinner, each with its own last bytes so no two are the same file. */
static uint8_t *zip_of_spinners(unsigned n, size_t *len)
{
	uint8_t (*copy)[sizeof spinner] = malloc(n * sizeof *copy);
	struct member *m = malloc(n * sizeof *m);
	uint8_t *z;
	unsigned i;

	for (i = 0; i < n; i++) {
		memcpy(copy[i], spinner, sizeof spinner);
		memcpy(copy[i] + sizeof spinner - 4u, &i, 4u);
		m[i].p = copy[i];
		m[i].n = sizeof spinner;
	}
	z = zip_stored(m, n, len);
	free(copy);
	free(m);
	return z;
}

/* ---- scanning ---------------------------------------------------------------- */

struct seen { unsigned objs, limit; };

static int on_object(const char *name, const void *bytes, uint64_t len,
		     const struct kof_result *res, void *user)
{
	struct seen *s = user;

	(void)name; (void)bytes; (void)len;
	s->objs++;
	if (res->broken == KOF_BROKEN_LIMIT)
		s->limit++;
	return 0;
}

static double now(void)
{
	struct timespec t;

	clock_gettime(CLOCK_MONOTONIC, &t);
	return (double)t.tv_sec + (double)t.tv_nsec / 1e9;
}

struct run { struct seen seen; struct kof_stats st; double secs; };

/* A fresh scanner per scan, so the counters are this scan's alone. */
static void scan(struct kof_engine *eng, const uint8_t *p, size_t n, uint64_t max_emu_insn,
		 struct run *r)
{
	struct kof_scanner *sc = kscan_new(eng);
	struct kof_scan_option opt;
	double t0;

	memset(r, 0, sizeof *r);
	memset(&opt, 0, sizeof opt);
	opt.max_object_depth = 4;
	opt.heur_level = 1;
	opt.max_emu_insn = max_emu_insn;
	t0 = now();
	kscan_bytes(sc, p, n, "tree", &opt, on_object, &r->seen);
	r->secs = now() - t0;
	r->st = *kscan_stats(sc);
	kscan_free(sc);
}

