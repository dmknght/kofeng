/*
 * hunt_emu_tree - what interpreting costs for a file made of many small objects.
 *
 * FOUND BY timing hostile-shaped files: a 1 KB PE64 whose code is `jmp $` (or a 5-byte xor loop)
 * costs 0.25 s (0.82 s) to scan - at the default heuristic level, where a rule's ask turns the
 * interpreter on - and a zip of 100 of them (18.9 KB; `kofscanner` default options) took 26 s
 * (83 s for the xor loop), 4.4 ms per input byte. The instruction budget was per OBJECT and a
 * small one has a floor (KGENOME_INSN_MIN, KGENOME_RESOLVE_MIN, EMU_INSN_MIN), so the cost grew
 * with the NUMBER of children, which a file chooses, and the size of the file did not bound it.
 *
 * FIXED by a tree-wide instruction allowance (kof_scan_ledger.emu_insn_left, sized from the ROOT
 * alone by oc_emu_tree_insn, taken by every emulator of the tree). What this holds:
 *
 *   1. a zip of 100 spinning PEs is bounded - by a deterministic count (runs made) and by time
 *      against one such PE scanned alone - and the bound is REPORTED: the children it refused
 *      read KOF_BROKEN_LIMIT, kof_stats.limit_hits and emu_budget_denied moved;
 *   2. the same inside a zip of zips (the allowance is the tree's, not each archive's);
 *   3. a legitimately large single file keeps its own per-object budget: nothing is refused
 *      and it runs for what its size allows;
 *   4. the host's allowance (kof_scan_option.max_emu_insn) is honoured, and the first runs of a
 *      tree keep their floor under it.
 *
 * The fixtures are stored zips built here from one 1025-byte PE (the report's file), so the
 * root is larger than the report's 18.9 KB, which only makes the allowance larger. Needs the
 * built database; run from the repository root.
 */

