/*
 * hunt_bz2_empty_first - a bzip2 file whose FIRST stream is empty, and an xz file of two streams.
 *
 * FOUND BY a differential of the engine's children against `bzip2 -dc` / `xz -dc` over
 * concatenated streams (bzcat_1, _3 and _11 of a generated set). `bzip2 -dc` writes the output
 * of every stream; the engine follows concatenated streams (bunzip.h) except when the first one
 * is the 14-byte empty stream: bz2_parse set KOF_BZ2_ANOM_EMPTY from the first stream alone and
 * the module returned on it, so `bz2(b"") + bz2(payload)` opened nothing. Fixed in
 * bz2_parse.c (empty means nothing FOLLOWS); asserted here by CONTENT.
 *
 * The xz half was a KNOWN MISS (finding H6): the parser found the footer from the END of the file, so a
 * file of two streams opened the LAST stream's blocks only and the first stream's payload was never
 * looked at (xz -dc decodes both), and kofscanner said "Damaged object" about a valid file. Fixed in
 * xz_parse.c (the streams are walked back from the last, stream padding tolerated) and asserted here
 * by CONTENT; tests/unit/xz_multistream.c is the differential against `xz -dc` and Python's lzma.
 *
 * Needs the built database (the unpackers are modules in it), run from the repository root.
 */

