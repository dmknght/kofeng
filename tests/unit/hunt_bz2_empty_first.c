struct seen {
	uint64_t want_n;
	const char *want_text;     /* NULL: only the length is asserted */
	int      hit, objects;
	uint64_t other_n;
	int      other_hit;
};

static int on_object(const char *name, const void *bytes, uint64_t len,
		     const struct kof_result *res, void *user)
{
	struct seen *s = user;

	(void)name;
	(void)res;
	s->objects++;
	if (len == s->want_n && bytes) {
		if (!s->want_text || memcmp(bytes, s->want_text, 27) == 0)
			s->hit++;
	}
	if (s->other_n && len == s->other_n)
		s->other_hit++;
	return 0;
}

static struct seen scan(struct kof_scanner *sc, const uint8_t *p, size_t n, uint64_t want_n,
			const char *text, uint64_t other_n)
{
	struct kof_scan_option opt;
	struct seen s;

	memset(&opt, 0, sizeof opt);
	memset(&s, 0, sizeof s);
	opt.max_object_depth = 4;
	opt.heur_level = 1;
	opt.emu_forbidden = 1;
	s.want_n = want_n;
	s.want_text = text;
	s.other_n = other_n;
	kscan_bytes(sc, p, n, "t.bz2", &opt, on_object, &s);
	return s;
}

int main(void)
{
	struct kof_engine *eng = keng_open("build/release/databases");
	struct kof_scanner *sc;
	uint8_t buf[1024];
	size_t n;
	struct seen s;

	if (!eng) {
		printf("hunt_bz2_empty_first: no database (run from the repository root after make): nothing tested\n");
		return 1;
	}
	sc = kscan_new(eng);
	CK(sc != NULL);
	if (!sc)
		return 1;

	/* empty + payload: the payload is the child */
	memcpy(buf, empty_stream, sizeof empty_stream);
	memcpy(buf + sizeof empty_stream, payload_stream, sizeof payload_stream);
	n = sizeof empty_stream + sizeof payload_stream;
	s = scan(sc, buf, n, 2800, "hello second stream payload ", 0);
	CK(s.hit == 1);

	/* payload + empty + payload: one child holding both (12800 bytes) */
	memcpy(buf, first_stream, sizeof first_stream);
	n = sizeof first_stream;
	memcpy(buf + n, empty_stream, sizeof empty_stream);
	n += sizeof empty_stream;
	memcpy(buf + n, payload_stream, sizeof payload_stream);
	n += sizeof payload_stream;
	s = scan(sc, buf, n, 12800, NULL, 0);
	CK(s.hit == 1);

	/* empty + empty + payload */
	memcpy(buf, empty_stream, sizeof empty_stream);
	memcpy(buf + sizeof empty_stream, empty_stream, sizeof empty_stream);
	memcpy(buf + 2u * sizeof empty_stream, payload_stream, sizeof payload_stream);
	s = scan(sc, buf, 2u * sizeof empty_stream + sizeof payload_stream, 2800, NULL, 0);
	CK(s.hit == 1);

	/* a lone empty stream still makes no child: one object, the file itself */
	s = scan(sc, empty_stream, sizeof empty_stream, 1, NULL, 0);
	CK(s.objects == 1);
	/* an empty stream followed by garbage that is not a stream: still nothing to open */
	memcpy(buf, empty_stream, sizeof empty_stream);
	memset(buf + sizeof empty_stream, 'x', 40);
	s = scan(sc, buf, sizeof empty_stream + 40u, 1, NULL, 0);
	CK(s.objects == 1);

	/* xz, two streams: the FIRST stream's 10000-byte payload should be a child */
	s = scan(sc, xz_two_streams, sizeof xz_two_streams, 10000, NULL, 2800);
	CK(s.other_hit >= 1);                           /* the last stream */
	CK(s.hit >= 1);                                 /* and the first stream, xz -dc writes both */
	CK(s.objects == 3);                             /* the file and the two payloads: no Damaged object */

	kscan_free(sc);
	keng_close(eng);
	if (failures)
		return 1;
	printf("hunt_bz2_empty_first: ok\n");
	return 0;
}
