#define _GNU_SOURCE

/*
 * tagcat_store.c - the tag catalog on disk: one file per distinct pair of sets (objects, activities), several tags in one file. The
 * format is described at "STORAGE" in tagcat.h. The directory (list, sorted read, write, remove), the ids and the line helpers are
 * catstore.c's, the same code as the family catalog; what is here is only what a tag file says and which file a tag belongs to.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "../kofcore/kofmod/kofsig.h"   /* diseaselist.h */
#include "tagcat.h"

static const char kw_name[] = "KOF_TAG_NAME";
static const char kw_acts[] = "KOF_TAG_ACTS";
static const char kw_objs[] = "KOF_TAG_OBJS";
static const char kw_header[] = "// Generated by Manage > Syndromes; edit by hand with care.";
static const char pre_act[] = "KOF_DISEASE_ACT_";
static const char pre_obj[] = "KOF_DISEASE_OBJ_";

/* ---- the file name of a pair of sets -------------------------------------------------------------------------------------- */

static int word_cmp(const void *a, const void *b)
{
	return strcmp(*(const char *const *)a, *(const char *const *)b);
}

/* The words of the set `mask` (bit v = value v of a list of `n` selectable values, `word(i)` spells the i-th) sorted and joined with '-'
 * into out[cap]; `none` when the set is empty. Returns the characters written (cap too small: 0 and an empty string). */
static size_t set_words(uint32_t mask, uint32_t n, const char *(*word)(uint32_t i), uint32_t (*value)(uint32_t i), const char *none,
			char *out, size_t cap)
{
	const char *w[32];
	uint32_t i, k = 0u;
	size_t at = 0u;

	for (i = 0; i < n && k < 32u; i++)
		if (mask >> value(i) & 1u)
			w[k++] = word(i);
	if (!k)
		w[k++] = none;
	qsort(w, k, sizeof w[0], word_cmp);
	for (i = 0; i < k; i++) {
		size_t l = strlen(w[i]);

		if (at + l + (i ? 1u : 0u) + 1u > cap) {
			if (cap)
				out[0] = 0;
			return 0u;
		}
		if (i)
			out[at++] = '-';
		memcpy(out + at, w[i], l);
		at += l;
	}
	out[at] = 0;
	return at;
}

void kof_tagcat_file_name(uint32_t acts, uint32_t objs, char *out, size_t cap)
{
	char o[160], a[160];

	if (!cap)
		return;
	out[0] = 0;
	if (!set_words(objs, kof_tagcat_obj_count(), kof_tagcat_obj_name, kof_tagcat_obj_value, "none", o, sizeof o) ||
	    !set_words(acts, kof_tagcat_act_count(), kof_tagcat_act_name, kof_tagcat_act_value, "none", a, sizeof a))
		return;
	if (strlen(o) + strlen(a) + 4u > cap)
		return;
	snprintf(out, cap, "%s_%s.c", o, a);
}

/* ---- which file a tag is in: the distinct pairs of sets, in the order their first tag appears ---------------------------- */

static int same_pair(const struct kof_tagcat *c, uint32_t a, uint32_t b)
{
	return c->tag[a].acts == c->tag[b].acts && c->tag[a].objs == c->tag[b].objs;
}

/* Is tag i the first of its pair? */
static int first_of_pair(const struct kof_tagcat *c, uint32_t i)
{
	uint32_t j;

	for (j = 0; j < i; j++)
		if (same_pair(c, j, i))
			return 0;
	return 1;
}

uint32_t kof_tagcat_file_count(const struct kof_tagcat *c)
{
	uint32_t i, n = 0u;

	for (i = 0; i < c->n; i++)
		n += (uint32_t)first_of_pair(c, i);
	return n;
}

/* The index of the first tag of file g, or UINT32_MAX. */
static uint32_t file_first(const struct kof_tagcat *c, uint32_t g)
{
	uint32_t i;

	for (i = 0; i < c->n; i++)
		if (first_of_pair(c, i) && g-- == 0u)
			return i;
	return UINT32_MAX;
}

void kof_tagcat_file_of(const struct kof_tagcat *c, uint32_t g, char *out, size_t cap)
{
	uint32_t t = file_first(c, g);

	if (t == UINT32_MAX) {
		if (cap)
			out[0] = 0;
		return;
	}
	kof_tagcat_file_name(c->tag[t].acts, c->tag[t].objs, out, cap);
}

/* ---- writing ---------------------------------------------------------------------------------------------------------- */

/* The identifier of value v of a list: prefix and the word in capitals. */
static size_t put_ident(char *out, size_t cap, const char *prefix, const char *word)
{
	size_t k = 0, i;

	for (i = 0; prefix[i] && k + 1u < cap; i++)
		out[k++] = prefix[i];
	for (i = 0; word[i] && k + 1u < cap; i++)
		out[k++] = word[i] >= 'a' && word[i] <= 'z' ? (char)(word[i] - 32) : word[i];
	if (cap)
		out[k] = 0;
	return k;
}

size_t kof_tagcat_file_text(const struct kof_tagcat *c, uint32_t g, char *out, size_t cap)
{
	size_t at = 0;
	uint32_t first = file_first(c, g), i, k, n;
	char ident[48];

#define PUT(...) do { int k_ = snprintf(out ? out + at : NULL, out && at < cap ? cap - at : 0u, __VA_ARGS__); at += (size_t)k_; } while (0)
	if (first == UINT32_MAX)
		return 0u;
	PUT("%s\n", kw_header);
	for (i = first; i < c->n; i++) {
		if (!same_pair(c, first, i))
			continue;
		PUT("\n");
		if (c->tag[i].comment[0])
			PUT("// %s\n", c->tag[i].comment);
		PUT("%s(\"%s\");\n", kw_name, c->tag[i].name);
		PUT("%s(", kw_acts);
		n = kof_tagcat_act_count();
		for (k = 0; k < n; k++)
			if (c->tag[i].acts >> kof_tagcat_act_value(k) & 1u) {
				put_ident(ident, sizeof ident, pre_act, kof_tagcat_act_name(k));
				PUT("%s%s", c->tag[i].acts & ((1u << kof_tagcat_act_value(k)) - 1u) ? ", " : "", ident);
			}
		PUT(");\n%s(", kw_objs);
		n = kof_tagcat_obj_count();
		for (k = 0; k < n; k++)
			if (c->tag[i].objs >> kof_tagcat_obj_value(k) & 1u) {
				put_ident(ident, sizeof ident, pre_obj, kof_tagcat_obj_name(k));
				PUT("%s%s", c->tag[i].objs & ((1u << kof_tagcat_obj_value(k)) - 1u) ? ", " : "", ident);
			}
		PUT(");\n");
	}
#undef PUT
	return at;
}

/* ---- reading ---------------------------------------------------------------------------------------------------------- */

struct rd {
	struct kof_tagcat *c;
	int open;                       /* a block is being read */
	char name[KOF_TAGCAT_NAME_MAX + 2u];
	uint32_t acts, objs;
	int has_acts, has_objs;
	struct kof_catpend pend;        /* the comment lines read directly above (catstore.h; shared with the Pathogens reader) */
	char comment[KOF_TAGCAT_COMMENT_MAX + 2u];   /* the pending text taken by the open block's NAME line */
};

/* The block read so far becomes a tag of the catalog (the rules of add). 0 on success, else the status's text in *why. */
static int commit(struct rd *r, const char **why)
{
	enum kof_tagcat_status st;
	struct kof_tagcat_fields f;

	if (!r->open)
		return 0;
	r->open = 0;
	f.name = r->name;
	f.comment = r->comment;
	f.acts = r->has_acts ? r->acts : 0u;
	f.objs = r->objs;
	st = kof_tagcat_load_tag(r->c, &f, NULL);
	if (st != KOF_TAGCAT_OK) {
		*why = kof_tagcat_why(r->c, st);
		return -1;
	}
	return 0;
}

/* The identifiers of a list call, "(A, B)" up to ");": the mask of the values whose identifier is prefix + capitals of a word of the list.
 * 1 and *mask on success, 0 on a word that is not one or a malformed call. */
static int set_list(const char *p, const char *prefix, int (*from)(const char *, uint8_t *), uint32_t *mask)
{
	char ident[48], word[48];
	size_t pl = strlen(prefix), i;
	uint32_t m = 0u;
	int comma = 0;                  /* the last thing read was a ',': a word must follow */

	for (;;) {
		uint8_t v;

		p = kof_catfmt_skip(p);
		if (kof_catfmt_call_end(p) && !comma) {
			*mask = m;
			return 1;
		}
		p = kof_catfmt_ident(p, ident, sizeof ident);
		if (strncmp(ident, prefix, pl) || !ident[pl] || strlen(ident + pl) >= sizeof word)
			return 0;
		for (i = 0; ident[pl + i]; i++)
			word[i] = ident[pl + i] >= 'A' && ident[pl + i] <= 'Z' ? (char)(ident[pl + i] + 32) : ident[pl + i];
		word[i] = 0;
		if (!from(word, &v))
			return 0;
		m |= 1u << v;
		p = kof_catfmt_skip(p);
		comma = *p == ',';
		if (comma)
			p++;
		else if (!kof_catfmt_call_end(p))
			return 0;
	}
}

static int act_from(const char *s, uint8_t *out)
{
	return kof_disease_act_from_name(s, out);
}

static int obj_from(const char *s, uint8_t *out)
{
	return kof_disease_obj_from_name(s, out);
}

/* One trimmed, NUL-terminated, non-empty line. 0: understood; 1: not understood (counted); -1: breaks a rule, *why says which. */
static int read_line(struct rd *r, char *t, const char **why)
{
	const char *p, *q;
	char name[KOF_NAME_MAX + 2u];

	if (!strcmp(t, kw_header))
		return 0;                       /* the file's own first line is not the first tag's comment */
	if (kof_catpend_line(&r->pend, t))
		return 0;
	if ((p = kof_catfmt_after(t, kw_name)) != NULL) {
		if (!(q = kof_catfmt_lit(p, name, sizeof name)) || !kof_catfmt_call_end(q)) {
			*why = "malformed line";
			return -1;
		}
		if (commit(r, why))
			return -1;
		memset(r->name, 0, sizeof r->name);
		memcpy(r->name, name, strlen(name) + 1u);
		memcpy(r->comment, r->pend.text, sizeof r->comment);
		kof_catpend_clear(&r->pend);
		r->open = 1;
		r->acts = r->objs = 0u;
		r->has_acts = r->has_objs = 0;
		return 0;
	}
	/* An old KOF_TAG_ID line is a line not understood: counted in `ignored`, never an error, not written back by Save. */
	if ((p = kof_catfmt_after(t, kw_acts)) != NULL) {
		if (!r->open || r->has_acts || !set_list(p, pre_act, act_from, &r->acts)) {
			*why = !r->open ? "activities before the tag name" : r->has_acts ? "activities given twice" : "malformed line";
			return -1;
		}
		r->has_acts = 1;
		return 0;
	}
	if ((p = kof_catfmt_after(t, kw_objs)) != NULL) {
		if (!r->open || r->has_objs || !set_list(p, pre_obj, obj_from, &r->objs)) {
			*why = !r->open ? "objects before the tag name" : r->has_objs ? "objects given twice" : "malformed line";
			return -1;
		}
		r->has_objs = 1;
		return 0;
	}
	return 1;
}

/* The line adapter of kof_catfmt_lines: a blank line, a line with a NUL and a line not understood end the comment above them; so does
 * every keyword but the NAME, which takes it. */
static int tag_line(void *user, char *t, const char **why)
{
	struct rd *r = user;
	int rc;

	if (!t || !*t) {
		kof_catpend_clear(&r->pend);
		return t ? 0 : 1;
	}
	rc = read_line(r, t, why);
	if (rc != 0 || t[0] != '/')
		kof_catpend_clear(&r->pend);
	return rc;
}

int kof_tagcat_load_text(struct kof_tagcat *c, const char *text, size_t len, uint32_t *ignored, const char **why)
{
	const uint32_t n = c->n;
	struct rd r;
	const char *w = "";
	uint32_t ign = 0u;

	memset(&r, 0, sizeof r);
	r.c = c;
	if (!kof_catfmt_lines(text, len, tag_line, &r, &ign, &w) || commit(&r, &w))
		goto fail;
	if (c->n == n) {
		w = "no tag name";
		goto fail;
	}
	if (ignored)
		*ignored = ign;
	if (why)
		*why = "";
	return 1;
fail:
	c->n = n;
	c->rev++;
	if (ignored)
		*ignored = 0u;
	if (why)
		*why = w;
	return 0;
}

/* ---- the directory ---------------------------------------------------------------------------------------------------- */

static int load_cb(void *user, const char *text, size_t len, uint32_t *ignored, const char **why)
{
	return kof_tagcat_load_text(user, text, len, ignored, why);
}

enum kof_catstore_io kof_tagcat_load(struct kof_tagcat *c, struct kof_catstore *s, const char *dir)
{
	struct kof_catstore_in in;

	in.user = c;
	in.load = load_cb;
	in.what = "syndromes";
	in.option = "--syndromes";
	c->n = 0u;
	c->rev++;
	return kof_catstore_load(s, dir, &in);
}

enum kof_catstore_io kof_tagcat_load_dir(struct kof_tagcat *c, const char *dir, char *note, size_t note_cap)
{
	struct kof_catstore *s = malloc(sizeof *s);
	enum kof_catstore_io io;

	if (!s) {
		if (note && note_cap)
			snprintf(note, note_cap, "out of memory");
		return KOF_CATSTORE_IO_FAIL;
	}
	io = kof_tagcat_load(c, s, dir);
	if (note && note_cap)
		snprintf(note, note_cap, "%s", s->note);
	free(s);
	return io;
}

/* ---- save ------------------------------------------------------------------------------------------------------------- */

static void out_name(void *user, uint32_t i, char *out, size_t cap)
{
	kof_tagcat_file_of(user, i, out, cap);
}

static size_t out_text(void *user, uint32_t i, char *out, size_t cap)
{
	return kof_tagcat_file_text(user, i, out, cap);
}

enum kof_catstore_io kof_tagcat_save(struct kof_tagcat *c, struct kof_catstore *s, const char *dir)
{
	struct kof_catstore_out o;

	o.user = c;
	o.n = kof_tagcat_file_count(c);
	o.name = out_name;
	o.text = out_text;
	o.what = "syndromes";
	o.option = "--syndromes";
	return kof_catstore_save(s, dir, &o);
}
