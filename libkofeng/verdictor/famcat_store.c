#include "famcat.h"

/* The three keywords of a file. The counter line's name and position are the owner's to review: its spelling is here and nowhere
 * else, the writer and the reader both use these. */
static const char kw_family[] = "KOF_MALWARE_FAMILY_NAME";
static const char kw_next[] = "KOF_MALWARE_NEXT_VARIANT";
static const char kw_variant[] = "KOF_MALWARE_VARIANT";
static const char kw_header[] = "// Generated by Manage > Pathogens; edit by hand with care.";
#define KW_ARGS(k) (sizeof(k) - 1u)

void kof_famcat_store_init(struct kof_famcat_store *s)
{
	memset(s, 0, sizeof *s);
}

void kof_famcat_file_name(const char *family, char *out, size_t cap)
{
	size_t i, n = strlen(family);

	if (cap < n + 3u) {
		if (cap)
			out[0] = 0;
		return;
	}
	for (i = 0; i < n; i++)
		out[i] = family[i] >= 'A' && family[i] <= 'Z' ? (char)(family[i] + 32) : family[i];
	out[n] = '.';
	out[n + 1u] = 'c';
	out[n + 2u] = 0;
}

/* ---- writing ---------------------------------------------------------------------------------------------------- */

size_t kof_famcat_family_text(const struct kof_famcat *c, uint32_t fam, char *out, size_t cap)
{
	size_t at = 0;
	uint32_t last = 0u, done, i, t;
	char letters[16];

#define PUT(...) do { int k_ = snprintf(out ? out + at : NULL, at < cap ? cap - at : 0u, __VA_ARGS__); at += (size_t)k_; } while (0)
	if (fam >= c->n_fam)
		return 0u;
	PUT("%s\n%s(\"%s\");\n", kw_header, kw_family, c->fam[fam].name);
	if (kof_famcat_letter_text(c->fam[fam].next, letters, sizeof letters))
		PUT("%s(\"%s\");\n", kw_next, letters);
	/* the variants in letter order: the smallest letter above the one written last, until none is left */
	for (done = 0; ; done++) {
		uint32_t best = UINT32_MAX;

		for (i = 0; i < c->n_var; i++)
			if (c->var[i].family == fam && c->var[i].letter > last &&
			    (best == UINT32_MAX || c->var[i].letter < c->var[best].letter))
				best = i;
		if (best == UINT32_MAX)
			break;
		last = c->var[best].letter;
		if (c->var[best].comment[0])
			PUT("// %s\n", c->var[best].comment);
		kof_famcat_letter_text(last, letters, sizeof letters);
		PUT("%s(\"%s\"", kw_variant, letters);
		for (t = 0; t < kof_famcat_type_count(); t++)
			if (c->var[best].types >> kof_famcat_type_value(t) & 1u)
				PUT(", %s", kof_maltype_ident(kof_famcat_type_value(t)));
		PUT(");\n");
	}
#undef PUT
	return at;
}

/* ---- reading ---------------------------------------------------------------------------------------------------- */

/* A string literal at p ("name", no escapes): copied without the quotes into out[cap]; the pointer past the closing quote, or NULL. */
static const char *lit(const char *p, char *out, size_t cap)
{
	size_t n = 0;

	if (*p != '"')
		return NULL;
	for (p++; *p && *p != '"'; p++) {
		if (*p == '\\' || n + 1u >= cap)
			return NULL;
		out[n++] = *p;
	}
	if (*p != '"')
		return NULL;
	out[n] = 0;
	return p + 1;
}

static const char *skip_blank(const char *p)
{
	while (*p == ' ' || *p == '\t')
		p++;
	return p;
}

/* The line after the keyword `kw` must open with "(" ; returns the text after it or NULL when the line is not that keyword's. */
static const char *after_keyword(const char *t, const char *kw, size_t kwlen)
{
	if (strncmp(t, kw, kwlen))
		return NULL;
	t = skip_blank(t + kwlen);
	return *t == '(' ? skip_blank(t + 1) : NULL;
}

/* The end of a call: ");" and nothing after. */
static int call_end(const char *p)
{
	p = skip_blank(p);
	return p[0] == ')' && p[1] == ';' && !*skip_blank(p + 2);
}

struct rd {
	struct kof_famcat *c;
	int have_fam;
	uint32_t fam;
	char pend[KOF_FAMCAT_COMMENT_MAX + 2u];   /* the comment lines directly above, joined; one over the limit so the check can say "too long" */
	size_t pl;
};

static void pend_clear(struct rd *r)
{
	r->pl = 0;
	r->pend[0] = 0;
}

static void pend_add(struct rd *r, const char *text)
{
	size_t n = strlen(text);

	if (!n)
		return;                 /* an empty comment line adds nothing (a joining blank would not survive the next read) */
	if (r->pl && r->pl < sizeof r->pend - 1u)
		r->pend[r->pl++] = ' ';
	if (n > sizeof r->pend - 1u - r->pl)
		n = sizeof r->pend - 1u - r->pl;
	memcpy(r->pend + r->pl, text, n);
	r->pl += n;
	r->pend[r->pl] = 0;
}

/* One trimmed, NUL-terminated, non-empty line. 0: understood; 1: not understood (counted); -1: breaks a rule, *why says which. */
static int read_line(struct rd *r, char *t, const char **why)
{
	const char *p, *q;
	char name[KOF_NAME_MAX + 2u], ident[48];
	enum kof_famcat_status st;

	if (t[0] == '/' && t[1] == '/') {
		t += 2;
		if (*t == ' ')
			t++;
		pend_add(r, t);
		return 0;
	}
	if ((p = after_keyword(t, kw_family, KW_ARGS(kw_family))) != NULL) {
		if (!(q = lit(p, name, sizeof name)) || !call_end(q)) {
			*why = "malformed line";
			return -1;
		}
		if (r->have_fam) {
			*why = "more than one family";
			return -1;
		}
		st = kof_famcat_load_family(r->c, name, &r->fam);
		r->have_fam = st == KOF_FAMCAT_OK;
		pend_clear(r);
		if (st != KOF_FAMCAT_OK)
			*why = kof_famcat_status_text(st);
		return st == KOF_FAMCAT_OK ? 0 : -1;
	}
	if ((p = after_keyword(t, kw_next, KW_ARGS(kw_next))) != NULL) {
		uint32_t n;

		if (!(q = lit(p, name, sizeof name)) || !call_end(q) || !(n = kof_famcat_letter_parse(name))) {
			*why = "malformed line";
			return -1;
		}
		st = r->have_fam ? kof_famcat_load_next(r->c, r->fam, n) : KOF_FAMCAT_NO_FAMILY;
		pend_clear(r);
		if (st != KOF_FAMCAT_OK)
			*why = r->have_fam ? kof_famcat_status_text(st) : "variant counter before the family name";
		return st == KOF_FAMCAT_OK ? 0 : -1;
	}
	if ((p = after_keyword(t, kw_variant, KW_ARGS(kw_variant))) != NULL) {
		uint32_t mask = 0u, n;

		if (!(q = lit(p, name, sizeof name)) || !(n = kof_famcat_letter_parse(name))) {
			*why = "malformed line";
			return -1;
		}
		for (q = skip_blank(q); *q == ','; q = skip_blank(q)) {
			size_t k = 0;
			int v;

			for (q = skip_blank(q + 1); (*q >= 'A' && *q <= 'Z') || (*q >= '0' && *q <= '9') || *q == '_'; q++)
				if (k + 1u < sizeof ident)
					ident[k++] = *q;
			ident[k] = 0;
			if (!kof_maltype_from_name(ident, &v)) {
				*why = "unknown malware type";
				return -1;
			}
			mask |= 1u << v;
		}
		if (!call_end(q)) {
			*why = "malformed line";
			return -1;
		}
		if (!r->have_fam) {
			*why = "variant before the family name";
			return -1;
		}
		st = kof_famcat_load_variant(r->c, r->fam, n, r->pend, mask, NULL);
		pend_clear(r);
		if (st != KOF_FAMCAT_OK)
			*why = kof_famcat_status_text(st);
		return st == KOF_FAMCAT_OK ? 0 : -1;
	}
	return 1;
}

int kof_famcat_load_text(struct kof_famcat *c, const char *text, size_t len, uint32_t *ignored, const char **why)
{
	const uint32_t n_fam = c->n_fam, n_var = c->n_var;
	struct rd r;
	size_t pos = 0;
	uint32_t ign = 0u;
	const char *w = "";
	char line[KOF_FAMCAT_LINE_MAX + 1u];

	memset(&r, 0, sizeof r);
	r.c = c;
	while (pos < len) {
		const char *e = memchr(text + pos, '\n', len - pos);
		size_t n = e ? (size_t)(e - (text + pos)) : len - pos;
		char *t = line, *end;
		int rc;

		if (n > KOF_FAMCAT_LINE_MAX) {
			w = "line too long";
			goto fail;
		}
		memcpy(line, text + pos, n);
		line[n] = 0;
		pos += n + (e ? 1u : 0u);
		if (strlen(line) != n) {                    /* a NUL inside the line: not text */
			ign++;
			pend_clear(&r);
			continue;
		}
		while (*t == ' ' || *t == '\t')
			t++;
		for (end = t + strlen(t); end > t && (end[-1] == ' ' || end[-1] == '\t' || end[-1] == '\r'); end--)
			;
		*end = 0;
		if (!*t) {
			pend_clear(&r);
			continue;
		}
		rc = read_line(&r, t, &w);
		if (rc < 0)
			goto fail;
		if (rc > 0) {
			ign++;
			pend_clear(&r);
		}
	}
	if (!r.have_fam) {
		w = "no family name";
		goto fail;
	}
	if (ignored)
		*ignored = ign;
	if (why)
		*why = "";
	return 1;
fail:
	c->n_fam = n_fam;
	c->n_var = n_var;
	kof_famcat_touch(c);
	if (ignored)
		*ignored = 0u;
	if (why)
		*why = w;
	return 0;
}

/* ---- the directory ---------------------------------------------------------------------------------------------- */

static int name_cmp(const void *a, const void *b)
{
	return strcmp(a, b);
}

static int is_regular(const char *path)
{
	struct stat st;

	return kof_lstat(path, &st) == 0 && S_ISREG(st.st_mode);
}

/* Read a whole file up to KOF_FAMCAT_FILE_MAX into buf[KOF_FAMCAT_FILE_MAX + 1]; returns the length, or SIZE_MAX with *why. */
static size_t read_file(const char *path, char *buf, const char **why)
{
	FILE *f;
	size_t n;

	if (!is_regular(path)) {
		*why = "not a regular file";
		return SIZE_MAX;
	}
	f = fopen(path, "rb");
	if (!f) {
		*why = "cannot be opened";
		return SIZE_MAX;
	}
	n = fread(buf, 1, KOF_FAMCAT_FILE_MAX + 1u, f);
	if (ferror(f))
		n = SIZE_MAX, *why = "read error";
	else if (n > KOF_FAMCAT_FILE_MAX)
		n = SIZE_MAX, *why = "file too big";
	fclose(f);
	return n;
}

#define BAD_SHOWN 3u

enum kof_famcat_io kof_famcat_load(struct kof_famcat *c, struct kof_famcat_store *s, const char *dir)
{
	static const char big[] = "name too long";
	char (*names)[KOF_FAMCAT_FILENAME_MAX + 1u];
	char bad[BAD_SHOWN][KOF_FAMCAT_FILENAME_MAX + 1u], path[1024], *buf;
	const char *why[BAD_SHOWN];
	uint32_t n_name = 0u, i, over = 0u;
	struct dirent *de;
	DIR *d;
	size_t at;

	kof_famcat_store_init(s);
	c->n_fam = c->n_var = 0u;
	kof_famcat_touch(c);
	if (!dir || !dir[0]) {
		snprintf(s->note, sizeof s->note, "no pathogens directory (--bases or --pathogens)");
		return KOF_FAMCAT_IO_NO_DIR;
	}
	d = opendir(dir);
	if (!d) {
		if (errno == ENOENT)
			return KOF_FAMCAT_IO_OK;            /* nothing saved yet: an empty catalog */
		snprintf(s->note, sizeof s->note, "cannot read %.120s: %s", dir, strerror(errno));
		return KOF_FAMCAT_IO_FAIL;
	}
	names = malloc(KOF_FAMCAT_FILES_MAX * sizeof *names);
	buf = malloc(KOF_FAMCAT_FILE_MAX + 1u);
	if (!names || !buf) {
		free(names);
		free(buf);
		closedir(d);
		snprintf(s->note, sizeof s->note, "out of memory");
		return KOF_FAMCAT_IO_FAIL;
	}
	while ((de = readdir(d)) != NULL) {
		size_t l = strlen(de->d_name);

		if (de->d_name[0] == '.' || l < 3u || strcmp(de->d_name + l - 2u, ".c"))
			continue;
		if (l > KOF_FAMCAT_FILENAME_MAX) {
			if (s->n_bad < BAD_SHOWN) {
				snprintf(bad[s->n_bad], sizeof bad[0], "%.*s...", (int)(sizeof bad[0] - 5u), de->d_name);
				why[s->n_bad] = big;
			}
			s->n_bad++;
		} else if (n_name < KOF_FAMCAT_FILES_MAX) {
			memcpy(names[n_name++], de->d_name, l + 1u);
		} else {
			over++;
		}
	}
	closedir(d);
	qsort(names, n_name, sizeof *names, name_cmp);
	for (i = 0; i < n_name; i++) {
		const char *w = "";
		uint32_t ign = 0u;
		size_t n;
		int ok = 0;

		if (snprintf(path, sizeof path, "%s/%s", dir, names[i]) >= (int)sizeof path) {
			w = "path too long";
		} else if ((n = read_file(path, buf, &w)) != SIZE_MAX) {
			ok = kof_famcat_load_text(c, buf, n, &ign, &w);
		}
		if (ok) {
			memcpy(s->file[s->n_file++], names[i], strlen(names[i]) + 1u);
			s->n_ignored += ign;
		} else {
			if (s->n_bad < BAD_SHOWN) {
				memcpy(bad[s->n_bad], names[i], strlen(names[i]) + 1u);
				why[s->n_bad] = w;
			}
			s->n_bad++;
		}
	}
	/* ONE line, the part a person needs first at the left (the dialog's rule cuts the right): the files not loaded by name, the lines
	 * not understood, then why the first file failed. */
	at = 0;
	if (s->n_bad || over) {
		at += (size_t)snprintf(s->note, sizeof s->note, "not loaded:");
		for (i = 0; i < s->n_bad && i < BAD_SHOWN; i++)
			at += (size_t)snprintf(s->note + at, sizeof s->note - at, i ? ", %s" : " %s", bad[i]);
		if (s->n_bad > BAD_SHOWN)
			at += (size_t)snprintf(s->note + at, sizeof s->note - at, " +%u more", (unsigned)(s->n_bad - BAD_SHOWN));
		if (over)
			at += (size_t)snprintf(s->note + at, sizeof s->note - at, " %u files over the limit of %u not read",
					       (unsigned)over, (unsigned)KOF_FAMCAT_FILES_MAX);
	}
	if (s->n_ignored)
		at += (size_t)snprintf(s->note + at, sizeof s->note - at, "%s%u line%s ignored", at ? "; " : "", (unsigned)s->n_ignored,
				       s->n_ignored == 1u ? "" : "s");
	if (s->n_bad)
		snprintf(s->note + at, sizeof s->note - at, " (%s: %s)", bad[0], why[0]);
	free(names);
	free(buf);
	return KOF_FAMCAT_IO_OK;
}

/* ---- save ------------------------------------------------------------------------------------------------------- */

/* Is `name` a file the store knows (loaded or written)? Letter case ignored: on a file system that ignores it, "Mirai.c" is the
 * file "mirai.c" would overwrite, and it is ours. */
static int known_at(const struct kof_famcat_store *s, const char *name)
{
	uint32_t i;

	for (i = 0; i < s->n_file; i++)
		if (!strcasecmp(s->file[i], name))
			return (int)i;
	return -1;
}

/* The same by exact name: the list entry a write is recorded in. */
static int listed_at(const struct kof_famcat_store *s, const char *name)
{
	uint32_t i;

	for (i = 0; i < s->n_file; i++)
		if (!strcmp(s->file[i], name))
			return (int)i;
	return -1;
}

static enum kof_famcat_io save_fail(struct kof_famcat_store *s, enum kof_famcat_io io, const char *what, const char *name)
{
	snprintf(s->note, sizeof s->note, "%s %s%s%s", what, name, errno && io == KOF_FAMCAT_IO_FAIL ? ": " : "",
		 errno && io == KOF_FAMCAT_IO_FAIL ? strerror(errno) : "");
	return io;
}

/* Does `a` name the very file `b` does (the same name on a file system that ignores letter case, or the same inode)? */
static int same_file(const char *a, const char *b)
{
	struct stat x, y;

	return kof_lstat(a, &x) == 0 && kof_lstat(b, &y) == 0 && x.st_ino != 0 && x.st_ino == y.st_ino && x.st_dev == y.st_dev;
}

enum kof_famcat_io kof_famcat_save(const struct kof_famcat *c, struct kof_famcat_store *s, const char *dir)
{
	char name[KOF_FAMCAT_FILENAME_MAX + 1u], other[KOF_FAMCAT_FILENAME_MAX + 1u], path[1024], path2[1024];
	uint8_t written[KOF_FAMCAT_FILES_MAX];
	struct stat st;
	uint32_t i, j;
	char *buf;

	s->note[0] = 0;
	errno = 0;
	if (!dir || !dir[0]) {
		snprintf(s->note, sizeof s->note, "no pathogens directory (--bases or --pathogens)");
		return KOF_FAMCAT_IO_NO_DIR;
	}
	if (c->n_fam > KOF_FAMCAT_FILES_MAX) {
		snprintf(s->note, sizeof s->note, "more than %u families", (unsigned)KOF_FAMCAT_FILES_MAX);
		return KOF_FAMCAT_IO_FAIL;
	}
	/* The whole catalog is checked before anything is written. */
	for (i = 0; i < c->n_fam; i++) {
		kof_famcat_file_name(c->fam[i].name, name, sizeof name);
		for (j = 0; j < i; j++) {
			kof_famcat_file_name(c->fam[j].name, other, sizeof other);
			if (!strcmp(name, other))
				return save_fail(s, KOF_FAMCAT_IO_COLLISION, "two families would share the file", name);
		}
		if (snprintf(path, sizeof path, "%s/%s", dir, name) >= (int)sizeof path)
			return save_fail(s, KOF_FAMCAT_IO_FAIL, "path too long", name);
		if (kof_lstat(path, &st) == 0 && known_at(s, name) < 0)
			return save_fail(s, KOF_FAMCAT_IO_COLLISION, "a file that was not loaded is in the way:", name);
	}
	{
		uint32_t extra = 0u;

		for (i = 0; i < s->n_file; i++) {
			int hit = 0;

			for (j = 0; j < c->n_fam; j++) {
				kof_famcat_file_name(c->fam[j].name, name, sizeof name);
				hit |= !strcmp(name, s->file[i]);
			}
			extra += !hit;
		}
		if (c->n_fam + extra > KOF_FAMCAT_FILES_MAX)
			return save_fail(s, KOF_FAMCAT_IO_FAIL, "too many files in", dir);
	}
	if (stat(dir, &st) != 0) {
		if (kof_mkdir(dir, 0777) != 0)
			return save_fail(s, KOF_FAMCAT_IO_FAIL, "cannot create", dir);
	} else if (!S_ISDIR(st.st_mode)) {
		errno = ENOTDIR;
		return save_fail(s, KOF_FAMCAT_IO_FAIL, "not a directory:", dir);
	}
	buf = malloc(KOF_FAMCAT_FILE_MAX);
	if (!buf)
		return save_fail(s, KOF_FAMCAT_IO_FAIL, "out of memory", "");
	memset(written, 0, sizeof written);
	/* Write: every family's file, directly (open, write, close). A file written is known from then on, so a failure half way leaves
	 * the store describing the directory as it is. */
	for (i = 0; i < c->n_fam; i++) {
		size_t n = kof_famcat_family_text(c, i, buf, KOF_FAMCAT_FILE_MAX);
		FILE *f;
		int k, bad;

		kof_famcat_file_name(c->fam[i].name, name, sizeof name);
		snprintf(path, sizeof path, "%s/%s", dir, name);
		errno = 0;
		if (n >= KOF_FAMCAT_FILE_MAX) {
			free(buf);
			return save_fail(s, KOF_FAMCAT_IO_FAIL, "file would be too big:", name);
		}
		f = kof_fopen_trunc_mode(path, 0666);
		bad = !f || fwrite(buf, 1, n, f) != n;
		if (f)
			bad |= fclose(f) != 0;
		if (bad) {
			int e = errno ? errno : EIO;

			free(buf);
			errno = e;
			return save_fail(s, KOF_FAMCAT_IO_FAIL, "cannot write", name);
		}
		k = listed_at(s, name);
		if (k < 0) {
			memcpy(s->file[s->n_file], name, strlen(name) + 1u);
			k = (int)s->n_file++;
		}
		written[k] = 1u;
	}
	free(buf);
	/* Remove the files of families that are gone (known files nothing was written to), unless one is the same file as a written one. */
	for (i = 0; i < s->n_file;) {
		int same = 0;

		if (written[i]) {
			i++;
			continue;
		}
		snprintf(path, sizeof path, "%s/%s", dir, s->file[i]);
		for (j = 0; j < s->n_file && !same; j++) {
			snprintf(path2, sizeof path2, "%s/%s", dir, s->file[j]);
			same = written[j] && same_file(path, path2);
		}
		errno = 0;
		if (!same && unlink(path) != 0 && errno != ENOENT)
			return save_fail(s, KOF_FAMCAT_IO_FAIL, "cannot remove", s->file[i]);
		memmove(s->file[i], s->file[i + 1u], (size_t)(s->n_file - i - 1u) * sizeof s->file[0]);
		memmove(&written[i], &written[i + 1u], s->n_file - i - 1u);
		s->n_file--;
	}
	return KOF_FAMCAT_IO_OK;
}
