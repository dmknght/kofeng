#define _GNU_SOURCE

/*
 * famcat_store.c - the malware family catalog on disk: one file per family, read back through the same calls the dialog uses (so one
 * set of rules). The format is described at "storage" in famcat.h. The directory (list, sorted read, write, remove) and the lines'
 * helpers are catstore.c's, shared with the tag catalog; what is here is only what a family file says.
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "../kofcore/kofmod/kofsig.h"   /* kof_maltype_ident, kof_maltype_from_name */
#include "famcat.h"

/* The keywords of a file. The counter line's name and position are the owner's to review: its spelling is here and nowhere else,
 * the writer and the reader both use these. */
static const char kw_family[] = "KOF_MALWARE_FAMILY_NAME";
static const char kw_next[] = "KOF_MALWARE_NEXT_VARIANT";
static const char kw_variant[] = "KOF_MALWARE_VARIANT";
static const char kw_header[] = "// Generated by Manage > Pathogens; edit by hand with care.";

void kof_famcat_store_init(struct kof_catstore *s)
{
	kof_catstore_init(s);
}

void kof_famcat_file_name(const char *family, char *out, size_t cap)
{
	size_t i, n = strlen(family);

	if (cap < n + 3u) {
		if (cap)
			out[0] = 0;
		return;
	}
	for (i = 0; i < n; i++)
		out[i] = family[i] >= 'A' && family[i] <= 'Z' ? (char)(family[i] + 32) : family[i];
	out[n] = '.';
	out[n + 1u] = 'c';
	out[n + 2u] = 0;
}

/* ---- writing ---------------------------------------------------------------------------------------------------- */

size_t kof_famcat_family_text(const struct kof_famcat *c, uint32_t fam, char *out, size_t cap)
{
	size_t at = 0;
	uint32_t last = 0u, done, i, t;
	char letters[16];

#define PUT(...) do { int k_ = snprintf(out ? out + at : NULL, out && at < cap ? cap - at : 0u, __VA_ARGS__); at += (size_t)k_; } while (0)
	if (fam >= c->n_fam)
		return 0u;
	PUT("%s\n%s(\"%s\");\n", kw_header, kw_family, c->fam[fam].name);
	/* The family's own comment: a `//` line directly above the counter line (never above KOF_MALWARE_FAMILY_NAME, which already has
	 * the fixed header line there; famcat.h "storage"). */
	if (c->fam[fam].comment[0])
		PUT("// %s\n", c->fam[fam].comment);
	/* The counter line (KOF_MALWARE_NEXT_VARIANT) is kept for now: a deleted HIGHEST letter leaves no other trace, and the menu of deleted
	 * names (kof_famcat_free_letter) counts the gaps below it from this value. The owner (2026-10-31): to be reviewed and improved later. */
	if (kof_famcat_letter_text(c->fam[fam].next, letters, sizeof letters))
		PUT("%s(\"%s\");\n", kw_next, letters);
	/* the variants in letter order: the smallest letter above the one written last, until none is left */
	for (done = 0; ; done++) {
		uint32_t best = UINT32_MAX;

		for (i = 0; i < c->n_var; i++)
			if (c->var[i].family == fam && c->var[i].letter > last &&
			    (best == UINT32_MAX || c->var[i].letter < c->var[best].letter))
				best = i;
		if (best == UINT32_MAX)
			break;
		last = c->var[best].letter;
		if (c->var[best].comment[0])
			PUT("// %s\n", c->var[best].comment);
		kof_famcat_letter_text(last, letters, sizeof letters);
		PUT("%s(\"%s\"", kw_variant, letters);
		for (t = 0; t < kof_famcat_type_count(); t++)
			if (c->var[best].types >> kof_famcat_type_value(t) & 1u)
				PUT(", %s", kof_maltype_ident(kof_famcat_type_value(t)));
		PUT(");\n");
	}
#undef PUT
	return at;
}

/* ---- reading ---------------------------------------------------------------------------------------------------- */

struct rd {
	struct kof_famcat *c;
	int have_fam;
	uint32_t fam;
	struct kof_catpend pend;        /* the comment lines directly above, joined (catstore.h; one over the limit so the check can say "too long") */
};

/* One trimmed, NUL-terminated, non-empty line. 0: understood; 1: not understood (counted); -1: breaks a rule, *why says which. */
static int read_line(struct rd *r, char *t, const char **why)
{
	const char *p, *q;
	char name[KOF_NAME_MAX + 2u], ident[48];
	enum kof_famcat_status st;

	if (kof_catpend_line(&r->pend, t))
		return 0;
	if ((p = kof_catfmt_after(t, kw_family)) != NULL) {
		if (!(q = kof_catfmt_lit(p, name, sizeof name)) || !kof_catfmt_call_end(q)) {
			*why = "malformed line";
			return -1;
		}
		if (r->have_fam) {
			*why = "more than one family";
			return -1;
		}
		/* The comment directly above THIS line is never the family's own: that position already holds the fixed header line
		 * (famcat.h "storage"), so it is discarded here, same as before. The family's own comment is the pend directly above
		 * KOF_MALWARE_NEXT_VARIANT, applied there. */
		st = kof_famcat_load_family(r->c, name, NULL, &r->fam);
		r->have_fam = st == KOF_FAMCAT_OK;
		kof_catpend_clear(&r->pend);
		if (st != KOF_FAMCAT_OK)
			*why = kof_famcat_why(r->c, st);
		return st == KOF_FAMCAT_OK ? 0 : -1;
	}
	/* the counter: kept for now, to be reviewed and improved later (see the writer, kof_famcat_family_text) */
	if ((p = kof_catfmt_after(t, kw_next)) != NULL) {
		uint32_t n;

		if (!(q = kof_catfmt_lit(p, name, sizeof name)) || !kof_catfmt_call_end(q) || !(n = kof_famcat_letter_parse(name))) {
			*why = "malformed line";
			return -1;
		}
		if (!r->have_fam) {
			kof_catpend_clear(&r->pend);
			*why = "variant counter before the family name";
			return -1;
		}
		/* A comment directly above the counter line is the FAMILY's own (famcat.h "storage"); applied once, here, before the
		 * counter itself is read back. */
		st = kof_famcat_set_family_comment(r->c, r->fam, r->pend.text);
		if (st == KOF_FAMCAT_OK)
			st = kof_famcat_load_next(r->c, r->fam, n);
		kof_catpend_clear(&r->pend);
		if (st != KOF_FAMCAT_OK)
			*why = kof_famcat_why(r->c, st);
		return st == KOF_FAMCAT_OK ? 0 : -1;
	}
	if ((p = kof_catfmt_after(t, kw_variant)) != NULL) {
		uint32_t mask = 0u, n;

		if (!(q = kof_catfmt_lit(p, name, sizeof name)) || !(n = kof_famcat_letter_parse(name))) {
			*why = "malformed line";
			return -1;
		}
		for (q = kof_catfmt_skip(q); *q == ','; q = kof_catfmt_skip(q)) {
			int v;

			q = kof_catfmt_ident(kof_catfmt_skip(q + 1), ident, sizeof ident);
			if (!kof_maltype_from_name(ident, &v)) {
				*why = "unknown malware type";
				return -1;
			}
			mask |= 1u << v;
		}
		if (!kof_catfmt_call_end(q)) {
			*why = "malformed line";
			return -1;
		}
		if (!r->have_fam) {
			*why = "variant before the family name";
			return -1;
		}
		st = kof_famcat_load_variant(r->c, r->fam, n, r->pend.text, mask, NULL);
		kof_catpend_clear(&r->pend);
		if (st != KOF_FAMCAT_OK)
			*why = kof_famcat_why(r->c, st);
		return st == KOF_FAMCAT_OK ? 0 : -1;
	}
	/* The id lines of a file an older tool saved (KOF_MALWARE_FAMILY_ID, KOF_MALWARE_VARIANT_ID) are lines not understood: counted in
	 * `ignored`, never an error, and Save does not write them back (an id is made from the names, catstore.h). */
	return 1;
}

/* The line adapter of kof_catfmt_lines: a blank line, a line with a NUL and a line not understood end the comment above them. */
static int family_line(void *user, char *t, const char **why)
{
	struct rd *r = user;
	int rc;

	if (!t || !*t) {
		kof_catpend_clear(&r->pend);
		return t ? 0 : 1;
	}
	rc = read_line(r, t, why);
	if (rc > 0)
		kof_catpend_clear(&r->pend);
	return rc;
}

int kof_famcat_load_text(struct kof_famcat *c, const char *text, size_t len, uint32_t *ignored, const char **why)
{
	const uint32_t n_fam = c->n_fam, n_var = c->n_var;
	struct rd r;
	const char *w = "";
	uint32_t ign = 0u;

	memset(&r, 0, sizeof r);
	r.c = c;
	if (!kof_catfmt_lines(text, len, family_line, &r, &ign, &w))
		goto fail;
	if (!r.have_fam) {
		w = "no family name";
		goto fail;
	}
	if (ignored)
		*ignored = ign;
	if (why)
		*why = "";
	return 1;
fail:
	c->n_fam = n_fam;
	c->n_var = n_var;
	kof_famcat_touch(c);
	if (ignored)
		*ignored = 0u;
	if (why)
		*why = w;
	return 0;
}

/* ---- the directory ---------------------------------------------------------------------------------------------- */

static int load_cb(void *user, const char *text, size_t len, uint32_t *ignored, const char **why)
{
	return kof_famcat_load_text(user, text, len, ignored, why);
}

enum kof_catstore_io kof_famcat_load(struct kof_famcat *c, struct kof_catstore *s, const char *dir)
{
	struct kof_catstore_in in;

	in.user = c;
	in.load = load_cb;
	in.what = "pathogens";
	in.option = "--pathogens";
	c->n_fam = c->n_var = 0u;
	kof_famcat_touch(c);
	return kof_catstore_load(s, dir, &in);
}

enum kof_catstore_io kof_famcat_load_dir(struct kof_famcat *c, const char *dir, char *note, size_t note_cap)
{
	struct kof_catstore *s = malloc(sizeof *s);
	enum kof_catstore_io io;

	if (!s) {
		if (note && note_cap)
			snprintf(note, note_cap, "out of memory");
		return KOF_CATSTORE_IO_FAIL;
	}
	io = kof_famcat_load(c, s, dir);
	if (note && note_cap)
		snprintf(note, note_cap, "%s", s->note);
	free(s);
	return io;
}

/* ---- save ------------------------------------------------------------------------------------------------------- */

static void out_name(void *user, uint32_t i, char *out, size_t cap)
{
	const struct kof_famcat *c = user;

	kof_famcat_file_name(c->fam[i].name, out, cap);
}

static size_t out_text(void *user, uint32_t i, char *out, size_t cap)
{
	return kof_famcat_family_text(user, i, out, cap);
}

enum kof_catstore_io kof_famcat_save(struct kof_famcat *c, struct kof_catstore *s, const char *dir)
{
	struct kof_catstore_out o;

	o.user = c;
	o.n = c->n_fam;
	o.name = out_name;
	o.text = out_text;
	o.what = "pathogens";
	o.option = "--pathogens";
	return kof_catstore_save(s, dir, &o);
}
