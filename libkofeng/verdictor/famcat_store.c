#define _GNU_SOURCE

/*
 * famcat_store.c - the malware family catalog on disk: one file per family, written directly, read back through the same calls the
 * dialog uses (so one set of rules). The format is described at "storage" in famcat.h. NOT a loader for hostile input: a small line
 * reader with named bounds; reading hostile files in depth is the later loader's job (owner), and an unknown line is counted, never
 * trusted.
 */

#include <dirent.h>
#include <errno.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <strings.h>
#include <sys/stat.h>
#include <unistd.h>

#include "../kofcore/kofmod/kofsig.h"   /* kof_maltype_ident, kof_maltype_from_name */
