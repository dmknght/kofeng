#ifndef KOF_TAGCAT_H
#define KOF_TAGCAT_H

/*
 * tagcat.h - the TAG CATALOG: the model and the rules behind Manage > Syndromes (the tag is the unit of classification).
 *
 * A TAG is a NAME, a SET of ACTIVITIES (at least one) and a SET of OBJECTS (may be empty). The activities and the objects are the
 * engine's two lists (kofmod/diseaselist.h: KOF_DISEASE_ACT_LIST, KOF_DISEASE_OBJ_LIST) and their words (kof_disease_act_name,
 * kof_disease_obj_name); this file keeps no second table of them. A set is a bit mask where bit v is the list's value v (values start
 * at 1: value 0 is NONE, so bit 0 is never set).
 *
 * HOW THE TWO SETS COMBINE INTO DISEASES (the (activity, object) pairs a verdict is made of) IS THE VERDICT DESIGN'S, LATER. This
 * catalog only stores what the person chose and checks it; it derives no pair and has no family or type.
 *
 * COMMENT. A tag carries one free-text comment (empty = none), the same thing a variant's comment is in famcat.h: bounded by the SAME
 * constant, KOF_CATSTORE_COMMENT_MAX (120, catstore.h; KOF_TAGCAT_COMMENT_MAX is that number), the character rule is the engine's
 * kof_comment_char, and the check is the one function both catalogs call (kof_catcomment_check). It is part of the tag: a change of it is
 * a change (revision, dirty, snapshot, restore).
 *
 * The catalog is an in-memory table in the CALLER's memory (kof_tagcat_init takes the array and its size; the library allocates
 * nothing and has no global). The bound is the caller's, is named by kof_tagcat_cap and a full table answers KOF_TAGCAT_FULL: an add
 * past it is refused and nothing is dropped. Tags are kept and listed in creation order. A NAME follows the engine's name rule
 * (kofmod/kofname.h kof_tag_name_ok: letters of either case, digits and '-', 1..KOF_NAME_MAX), and no two tags have names that differ only in
 * letter case (a name is one name in any case; a file name made from it is lower case). Add and rename and edit share ONE name check (tag_name_status in tagcat.c).
 *
 * A REVISION counter is bumped by every call that changes the catalog, so a viewer that derived something from it (rows, sizes)
 * recomputes only when the number moved. A refused call changes nothing and leaves the revision alone.
 *
 * ID. A tag has no stored id: its id is made from its name (catstore.h, kof_tagcat_id), so a rename is a new id and a change of the sets
 * keeps it. A name whose id another tag already has is refused (KOF_TAGCAT_ID_CLASH).
 *
 * STORAGE (tagcat_store.c; the directory is catstore.h's, the same code as Manage > Pathogens). The files are DATA, never compiled,
 * in one directory (bases/syndromes). ONE FILE PER DISTINCT PAIR OF SETS, named `<objects>_<activities>.c`: each set is its values'
 * words in ALPHABETICAL order (so adding a value to the engine's list renames no file) joined with '-' (a word holds no '-' or '_', so the name reads back one way), an empty object set is
 * "none": `file-network_scan-steal.c`, `none_hidden.c`. Tags that share both sets are in the same file, in creation order, each as a
 * block (a comment is `// ` lines directly above the NAME line, as a variant's is above its KOF_MALWARE_VARIANT line in the Pathogens
 * files; one reader, catstore.h kof_catpend_line; a blank line or a line not understood ends it; the file's own header line is not one):
 *     // Generated by Manage > Syndromes; edit by hand with care.
 *
 *     // Scans hosts before an attack
 *     KOF_TAG_NAME("Flood");
 *     KOF_TAG_ACTS(KOF_DISEASE_ACT_SCAN, KOF_DISEASE_ACT_STEAL);
 *     KOF_TAG_OBJS(KOF_DISEASE_OBJ_NETWORK, KOF_DISEASE_OBJ_FILE);
 * A block begins at its NAME line; an old KOF_TAG_ID line is read as a line not understood (counted as ignored) and not written back; OBJS may be missing or empty (no objects); ACTS is required. The file name is
 * not read back (a moved file is still read), Save rewrites the file each tag belongs to and removes the files of pairs that are gone.
 * A line that is not understood is counted and, as with the families, not written back.
 */

#include <stddef.h>
#include <stdint.h>

#include <kofmod/kofname.h>

#include "catstore.h"

#define KOF_TAGCAT_NAME_MAX KOF_NAME_MAX
#define KOF_TAGCAT_COMMENT_MAX KOF_CATSTORE_COMMENT_MAX   /* the one constant of both catalogs */

enum kof_tagcat_status {
	KOF_TAGCAT_OK = 0,
	KOF_TAGCAT_EMPTY,           /* no name */
	KOF_TAGCAT_TOO_LONG,        /* more than KOF_TAGCAT_NAME_MAX characters */
	KOF_TAGCAT_BAD_CHAR,        /* a character outside letters, digits and '-' */
	KOF_TAGCAT_DUPLICATE,       /* another tag has this name, letter case ignored */
	KOF_TAGCAT_NO_ACTIVITY,     /* a tag needs at least one activity */
	KOF_TAGCAT_BAD_ACTIVITY,    /* a bit that is not a value of the activity list */
	KOF_TAGCAT_BAD_OBJECT,      /* a bit that is not a value of the object list */
	KOF_TAGCAT_FULL,            /* the caller's table is full (kof_tagcat_cap) */
	KOF_TAGCAT_NO_TAG,          /* no such index */
	KOF_TAGCAT_ID_CLASH,        /* the name makes the id of another tag (catstore.h); kof_tagcat_why names both */
	KOF_TAGCAT_BAD_COMMENT,     /* a character kof_comment_char refuses (non-printable, '*' or '/') */
	KOF_TAGCAT_COMMENT_TOO_LONG /* more than KOF_TAGCAT_COMMENT_MAX characters */
};

struct kof_tagcat_tag {
	char     name[KOF_TAGCAT_NAME_MAX + 1];
	char     comment[KOF_TAGCAT_COMMENT_MAX + 1];   /* "" = none */
	uint32_t acts;              /* mask over enum kof_disease_act values */
	uint32_t objs;              /* mask over enum kof_disease_obj values; 0 = none chosen */
};

struct kof_tagcat {
	struct kof_tagcat_tag *tag;
	uint32_t cap, n;
	uint32_t rev;               /* bumped by every successful change */
	kof_catid_hash_fn hash;     /* the hash an id is made with (kof_tagcat_set_idhash: a test forces a collision); NULL = kof_catid_hash */
	void *hash_ud;
	char clash[2u * KOF_TAGCAT_NAME_MAX + 64u];   /* the text of the last KOF_TAGCAT_ID_CLASH refusal, both names (kof_tagcat_why) */
};

void kof_tagcat_init(struct kof_tagcat *c, struct kof_tagcat_tag *tag, uint32_t cap);
/* Set the hash ids are made with (a test passes one that collides); NULL goes back to kof_catid_hash. */
void kof_tagcat_set_idhash(struct kof_tagcat *c, kof_catid_hash_fn hash, void *ud);
uint32_t kof_tagcat_cap(const struct kof_tagcat *c);
/* One line for a dialog's error row ("" is not returned: OK is "ok"). */
const char *kof_tagcat_status_text(enum kof_tagcat_status st);

/* The selectable activities and objects: n of each, the i-th is the engine value kof_tagcat_act_value(i) (= i + 1), spelled by the
 * engine's own function. The masks of every selectable value are the only bits a set may hold. */
uint32_t kof_tagcat_act_count(void);
uint32_t kof_tagcat_act_value(uint32_t i);
const char *kof_tagcat_act_name(uint32_t i);
uint32_t kof_tagcat_obj_count(void);
uint32_t kof_tagcat_obj_value(uint32_t i);
const char *kof_tagcat_obj_name(uint32_t i);
uint32_t kof_tagcat_act_mask_all(void);
uint32_t kof_tagcat_obj_mask_all(void);

/* The name rule alone as a status (empty, too long, bad character); no catalog needed. */
enum kof_tagcat_status kof_tagcat_name_check(const char *name);

/* The comment rule alone as a status (OK, BAD_COMMENT, COMMENT_TOO_LONG); NULL and "" are fine. */
enum kof_tagcat_status kof_tagcat_comment_check(const char *comment);

/* Everything a person gives for a tag, as ONE request (the dialog's form): comment NULL = none. */
struct kof_tagcat_fields {
	const char *name;
	const char *comment;
	uint32_t    acts, objs;
};
/* Add / change a tag from all its fields; the rules of add and edit plus the comment rule, all or nothing. */
enum kof_tagcat_status kof_tagcat_add_fields(struct kof_tagcat *c, const struct kof_tagcat_fields *f, uint32_t *idx);
enum kof_tagcat_status kof_tagcat_edit_fields(struct kof_tagcat *c, uint32_t idx, const struct kof_tagcat_fields *f);
/* The comment of tag `idx` ("" when none or no such tag), and its change alone (the other fields stay). */
const char *kof_tagcat_comment(const struct kof_tagcat *c, uint32_t idx);
enum kof_tagcat_status kof_tagcat_set_comment(struct kof_tagcat *c, uint32_t idx, const char *comment);

/* Add a tag (creation order: it goes last) with no comment. On OK *idx is its index (idx may be NULL). */
enum kof_tagcat_status kof_tagcat_add(struct kof_tagcat *c, const char *name, uint32_t acts, uint32_t objs, uint32_t *idx);
/* Change tag `idx`: name, activities and objects together, or none of them; the rules of add, a tag may keep its own name (or change only
 * its case). The comment stays as it is. */
enum kof_tagcat_status kof_tagcat_edit(struct kof_tagcat *c, uint32_t idx, const char *name, uint32_t acts, uint32_t objs);
/* The three single changes. rename is the name rule of add and edit; set_acts and set_objs the set rules. */
enum kof_tagcat_status kof_tagcat_rename(struct kof_tagcat *c, uint32_t idx, const char *name);
enum kof_tagcat_status kof_tagcat_set_acts(struct kof_tagcat *c, uint32_t idx, uint32_t acts);
enum kof_tagcat_status kof_tagcat_set_objs(struct kof_tagcat *c, uint32_t idx, uint32_t objs);
/* Remove a tag; the others keep their order and the indices above it shift down by one. */
enum kof_tagcat_status kof_tagcat_delete(struct kof_tagcat *c, uint32_t idx);
/* The tag at `idx` in creation order, or NULL. */
const struct kof_tagcat_tag *kof_tagcat_get(const struct kof_tagcat *c, uint32_t idx);


/* ---- ids: made from the name (catstore.h), held nowhere ----------------------------------------------------------------- */

/* The id of the tag named `name` (letter case ignored, like the uniqueness rule), 0 when there is none; the id of tag index `idx`, 0 for an
 * index the catalog does not have. A rename of a tag changes its id. */
uint64_t kof_tagcat_id(const struct kof_tagcat *c, const char *name);
uint64_t kof_tagcat_id_at(const struct kof_tagcat *c, uint32_t idx);
/* A name that makes another tag's id is refused by add, edit, rename and the loader with KOF_TAGCAT_ID_CLASH, nothing changed. The line to
 * show for a refusal: the status text, and for KOF_TAGCAT_ID_CLASH both names. */
const char *kof_tagcat_why(const struct kof_tagcat *c, enum kof_tagcat_status st);
/* A loader's step: add a tag of the fields a file gave (comment "" = none). The rules of add. On OK *idx is its index (may be NULL). */
enum kof_tagcat_status kof_tagcat_load_tag(struct kof_tagcat *c, const struct kof_tagcat_fields *f, uint32_t *idx);

/* ---- the snapshot: what Discard goes back to ------------------------------------------------------------------------- */

/* `snap` is a catalog the caller initialised with an array at least as big as `c`'s tags (FULL otherwise). Copy c into snap; restore
 * copies it back. dirty: 1 when c differs from snap by value (count, order, names, comments, sets, ids). */
enum kof_tagcat_status kof_tagcat_snapshot(const struct kof_tagcat *c, struct kof_tagcat *snap);
enum kof_tagcat_status kof_tagcat_restore(struct kof_tagcat *c, const struct kof_tagcat *snap);
int kof_tagcat_dirty(const struct kof_tagcat *c, const struct kof_tagcat *snap);

/* ---- storage (tagcat_store.c) ------------------------------------------------------------------------------------------ */

#define KOF_TAGCAT_FILENAME_MAX KOF_CATSTORE_FILENAME_MAX

/* The file name of a pair of sets, `<objects>_<activities>.c` (see above), into out[cap]; "" when it does not fit. */
void kof_tagcat_file_name(uint32_t acts, uint32_t objs, char *out, size_t cap);
/* How many files the catalog needs (distinct pairs of sets), the name of file `g` and its text (snprintf rule; 0 for a `g` out of range). */
uint32_t kof_tagcat_file_count(const struct kof_tagcat *c);
void kof_tagcat_file_of(const struct kof_tagcat *c, uint32_t g, char *out, size_t cap);
size_t kof_tagcat_file_text(const struct kof_tagcat *c, uint32_t g, char *out, size_t cap);
/* Read one file's text into the catalog: all of it or none. `ignored` gets the number of lines not understood, `why` the reason on
 * failure. Returns 1 when loaded. */
int kof_tagcat_load_text(struct kof_tagcat *c, const char *text, size_t len, uint32_t *ignored, const char **why);
/* Empty the catalog and load every `*.c` of `dir`; a file that does not load is counted and named in s->note. A directory that does not
 * exist is an empty catalog. */
enum kof_catstore_io kof_tagcat_load(struct kof_tagcat *c, struct kof_catstore *s, const char *dir);
/* The same without a store the caller keeps, for a build tool that only reads. The catalog's array is the caller's and bounds what is read. */
enum kof_catstore_io kof_tagcat_load_dir(struct kof_tagcat *c, const char *dir, char *note, size_t note_cap);
/* Write every file into `dir` (created when missing; names and sets only, no id), remove the files of pairs that are gone. Refused,
 * with nothing written, when a file that was not loaded is in the way. */
enum kof_catstore_io kof_tagcat_save(struct kof_tagcat *c, struct kof_catstore *s, const char *dir);

#endif /* KOF_TAGCAT_H */
