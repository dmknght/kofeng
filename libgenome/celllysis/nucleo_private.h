struct kgenome_nucleo_names {
	uint8_t                              target;   /* enum kgenome_nucleo_target */
	uint8_t                              fold;     /* names are not case sensitive (php, vbscript, batch, powershell, cfml, .NET) */
	const struct kgenome_nucleo_namerow *row;
	uint32_t                             n;
};

/*
 * THE INDEX OVER THE TABLES, one entry per table in the order of `tables[]` in nucleo.c (nucleo_index.c, GENERATED by tools/gen_nucleo_index.py): `slot` holds `cap`
 * (a power of two) row positions + 1, 0 empty, by the FNV-1a hash of the name (folded for a `fold` table) with linear probing; `n` is the table's row count, which
 * the test checks against the table. Const: nothing is built at run time.
 */
struct kgenome_nucleo_index {
	uint32_t        cap, n;
	const uint16_t *slot;
};
