const struct kgenome_textual_perl_kw_row *kgenome_textual_perl_kw(const uint8_t *w, uint32_t len)
{
	uint32_t lo = 0, hi = (uint32_t)(sizeof kw / sizeof kw[0]);

	while (lo < hi) {
		uint32_t mid = lo + (hi - lo) / 2u, nl = (uint32_t)strlen(kw[mid].name);
		int c = memcmp(w, kw[mid].name, len < nl ? len : nl);

		if (c == 0)
			c = len < nl ? -1 : len > nl ? 1 : 0;
		if (c == 0)
			return &kw[mid];
		if (c < 0)
			hi = mid;
		else
			lo = mid + 1u;
	}
	return NULL;
}
