/*
 * perl_kw.c - the words of perl that change how the bytes after them are read.
 *
 * A "/" is the start of a pattern where a term is expected and a division after one, and perl does not mark
 * which: it is the word before. So the lexer needs to know, of every word, whether a term or an operator follows,
 * and nothing else about it. The list is perlfunc's own (the `=item` headings of perlfunc.pod, perl 5.40), plus
 * the words of the syntax (if unless while until for foreach elsif, and or not xor, lt gt le ge eq ne cmp x isa,
 * given when default, try catch finally defer, the phase blocks, class field ADJUST, __END__ __DATA__).
 *   - KGENOME_TEXTUAL_PERL_KW_TERM: what yields a value or takes an argument it can do without, so an operator may come next.
 *     "shift // 0" and "time / 60" are real code and "shift /x/" is not; a function that always has an argument
 *     ("lc", "join") is KGENOME_TEXTUAL_PERL_KW_ARGS instead.
 *   - KGENOME_TEXTUAL_PERL_KW_ARGS: a term follows. "split /,/", "return /x/", "and /x/" are patterns and "print <<EOF" is a
 *     here-document. A user's function is in neither list: it is a name, and "foo /2" divides ([Unverified]
 *     against perl for a sub with a prototype: perl asks the prototype, the lexer cannot).
 *   - `block`: a "{" right after it opens a block (do, eval, else, map, grep, sort, BEGIN) and not a hash. 2 says the block is a
 *     TERM: a "/" after the "}" of a `do` or an `eval` or an anonymous `sub` is a division ("do { 1 } / 2"), where after the "}" of
 *     an `else` or a `map` a statement or a list begins.
 *
 * Sorted by byte order (the test checks it), found by binary search: 261 words and the lexer asks once per word.
 */

