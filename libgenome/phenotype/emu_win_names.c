/*
 * emu_win_names.c - the names the modelled Windows libraries export and have no behaviour for.
 *
 * WHY THEY ARE HERE. A protector does not import what it uses: it walks a library's export directory by
 * hashing every name, and patches the first bytes of each function it finds (VirtualProtect, then a jump).
 * A name this environment does not list is a lookup that ends at the end of the table with no answer, and
 * the protector carries the zero it got into the next step - measured on five Themida samples, a call to
 * VirtualProtect(0, 5, ...) and, a few thousand instructions later, a store through a pointer built from
 * data nobody wrote. With the names below, and nothing else changed, the same loaders ran on to the
 * function that hands over to the program (see the note beside KGENOME_EMU_WIN_MOD_MSCOREE).
 *
 * A name here has a stub in its library and answers 0, which is what the null-call policy answers for a
 * name the environment lacks. It is counted (kgenome_emu_unmodelled_calls), not ignored. A name with a
 * handler is in win_api[] in emu_win.c and wins when a name is in both.
 *
 * WHERE THE LISTS CAME FROM, AND WHY EACH NAME IS KNOWN TO BE REAL. Two sources, both evidence and neither a
 * guess: the names the import tables of 29,518 files (Bazaar 2026.08, the Sality set, the MalwareLab directory)
 * bind to these libraries - a binary that runs imported a name that exists - and the names the Themida
 * loaders themselves resolved from a candidate dictionary (a hash match is an existing export), plus
 * ntdll!DbgBreakPoint and DbgUiRemoteBreakin, which they patch. No file of the real libraries was read, so the
 * lists are a LOWER bound on what the libraries export, and a name outside them still gets the null answer.
 *
 * THE ARGUMENT COUNT is the i386 stdcall one (the callee pops it) and 0xff where it is not known: such a stub
 * returns with no cleanup, and a call of one is counted as guessed (kgenome_emu_unmodelled_guessed), because a guess about
 * the stack is a result that may be wrong and must say so. A cdecl varargs function (wsprintf) is 0.
 *
 * WHAT A LIST COSTS. A protector's lookup is a walk down the sorted names, so a longer list is more
 * instructions per lookup (the Themida samples spend about 5-7 percent of their run in it). That is a cost
 * of being a faithful library and is paid by the run that asked.
 */
